// Writes patterns.go: the classifier pattern lists of pi-ai utils/overflow.ts and utils/retry.ts, copied from the pinned source.
import { readFileSync, writeFileSync } from "node:fs";
const PI = process.env.PI_MAIN;
const retry = readFileSync(`${PI}/packages/ai/src/utils/retry.ts`, "utf8");
const overflow = readFileSync(`${PI}/packages/ai/src/utils/overflow.ts`, "utf8");
const list = (src, name) => {
	const m = new RegExp(`const ${name} = buildProviderErrorPattern\\(\\[([\\s\\S]*?)\\]\\);`).exec(src);
	return [...m[1].matchAll(/^\s*"((?:[^"\\]|\\.)*)",/gm)].map((x) => JSON.parse(`"${x[1]}"`));
};
const regexes = (src, name) => {
	const m = new RegExp(`const ${name} = \\[([\\s\\S]*?)\\n\\];`).exec(src);
	return [...m[1].matchAll(/^\s*\/(.*)\/i,/gm)].map((x) => x[1]);
};
const one = (src, name) => new RegExp(`const ${name} = /(.*)/i;`).exec(src)[1];
const q = (s) => "`" + s.replaceAll("`", "` + \"`\" + `") + "`";
const block = (name, xs) => `// Read-only: assigned once at initialization.\nvar ${name} = []string{\n${xs.map((x) => `\t${q(x)},`).join("\n")}\n}\n`;
const out = `// Code generated by oracle/gen_patterns.mjs from pi-ai utils/overflow.ts and utils/retry.ts; DO NOT EDIT.

// Ports packages/ai/src/utils/overflow.ts (OVERFLOW_PATTERNS, NON_OVERFLOW_PATTERNS)
// Ports packages/ai/src/utils/retry.ts (RETRYABLE_PROVIDER_ERROR_PATTERN, NON_RETRYABLE_PROVIDER_LIMIT_ERROR_PATTERN)
package turn

${block("nonRetryablePatterns", list(retry, "NON_RETRYABLE_PROVIDER_LIMIT_ERROR_PATTERN"))}
${block("retryablePatterns", list(retry, "RETRYABLE_PROVIDER_ERROR_PATTERN"))}
${block("overflowPatterns", regexes(overflow, "OVERFLOW_PATTERNS"))}
${block("nonOverflowPatterns", regexes(overflow, "NON_OVERFLOW_PATTERNS"))}
const cerebrasBodylessPattern = ${q(one(overflow, "CEREBRAS_BODYLESS_OVERFLOW_PATTERN"))}
`;
writeFileSync(new URL("../patterns.go", import.meta.url), out);
console.log("ok");
