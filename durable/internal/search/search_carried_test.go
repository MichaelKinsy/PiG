//go:embed testdata/ranker_goldens.json
var rankerGoldens []byte

// The goldens are Pi's own ranking at 79006f06, the newest carried commit of search.ts (testdata/gen_ranker_goldens.mjs), over random documents with namespace texts, names that share words with the queries,
// names with U+0130, the Kelvin sign and a character outside the BMP, words of other scripts and limits: the names and their order must match exactly. The pinned Pi's oracle (search_pi_oracle_test.go) cannot supply
// them: it scores the name as part of the text and has no namespace text.
func TestRankDocumentsMatchesPiTheLatestCarriedRanker(t *testing.T) {
	var probes []struct {
		Documents []struct {
			Name          string `json:"name"`
			Text          string `json:"text"`
			NamespaceText string `json:"namespaceText"`
		} `json:"documents"`
		Query  string   `json:"query"`
		Limit  int      `json:"limit"`
		Ranked []string `json:"ranked"`
	}
	if err := json.Unmarshal(rankerGoldens, &probes); err != nil {
		t.Fatal(err)
	}
	ranked, ordered := 0, 0
	for i, probe := range probes {
		// A Binary without the word dictionaries (D92) keeps dictionary scripts whole, so a probe that holds one is outside what Pi's answer pins there.
		if stripsDictionaries() {
			words := probe.Query
			for _, d := range probe.Documents {
				words += d.Name + d.Text + d.NamespaceText
			}
			if usesDictionary(words) {
				continue
			}
		}
		documents := make([]Document, len(probe.Documents))
		for j, d := range probe.Documents {
			documents[j] = Document(d)
		}
		got := RankDocuments(probe.Query, documents, probe.Limit)
		ranked += len(got)
		if len(got) > 1 {
			ordered++
		}
		if !slices.Equal(got, probe.Ranked) {
			t.Errorf("probe %d %q limit %d: got %v, want %v", i, probe.Query, probe.Limit, got, probe.Ranked)
		}
	}
	if ranked < 150 || ordered < 50 {
		t.Fatalf("%d matches over %d probes, %d with an order to check: the goldens do not exercise the ranker", ranked, len(probes), ordered)
	}
}

