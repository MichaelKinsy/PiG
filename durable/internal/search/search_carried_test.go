// The goldens are Pi's own tokenize at 79006f06 (the coding agent's and durable's copies agree; testdata/tokenize_goldens.json is generated by the coding agent's toolsearch/testdata/gen_tokenize_goldens.mjs) over every script class:
// Latin with diacritics and in NFD, Cyrillic, Greek, Arabic, Hebrew, the Indic scripts, Hangul, Armenian, Georgian, Ethiopic, Tibetan, Mongolian and Cherokee, digits, and the scripts ICU segments with a dictionary
// (Han, Hiragana, Katakana, Thai, Lao, Khmer, Myanmar), phrases and random draws of each, mixed-script texts, lone surrogates and the Southeast Asian fixture of internal/wordsegmenter. Every term must match exactly; a Piglet
// that strips the word dictionaries keeps dictionary scripts whole and so skips the probes that hold one.
func TestTokenizeMatchesPiOnEveryScriptClass(t *testing.T) {
	var probes []struct {
		Class  string   `json:"class"`
		Text   string   `json:"text"`
		Tokens []string `json:"tokens"`
	}
	if err := jsstring.UnmarshalKeepingSurrogates(tokenizeGoldens, &probes); err != nil {
		t.Fatal(err)
	}
	stripped := stripsDictionaries()
	compared, nonEmpty := 0, 0
	for _, probe := range probes {
		if stripped && usesDictionary(probe.Text) {
			continue
		}
		compared++
		if len(probe.Tokens) > 0 {
			nonEmpty++
		}
		if got := searchtext.Tokenize(probe.Text); !slices.Equal(got, probe.Tokens) {
			t.Errorf("%s: tokenize(%q) = %q, Pi %q", probe.Class, probe.Text, got, probe.Tokens)
		}
	}
	if nonEmpty < 2000 || (!stripped && compared != len(probes)) {
		t.Errorf("%d probes compared of %d, %d with terms: the goldens do not exercise the tokenizer", compared, len(probes), nonEmpty)
	}
}
