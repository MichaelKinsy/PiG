// stripsDictionaries reports whether this process has no ICU word dictionaries (a pig_strip_word_dictionaries build, D92), where a dictionary script's run is one word.
func stripsDictionaries() bool { return pigstrip.Has(pigstrip.ListFeatures, pigstrip.WordDictionaries) }

// usesDictionary reports whether the text holds a character of a script that ICU segments with a dictionary.
func usesDictionary(text string) bool {
	for _, r := range text {
		if unicode.In(r, unicode.Han, unicode.Hiragana, unicode.Katakana, unicode.Thai, unicode.Lao, unicode.Khmer, unicode.Myanmar) {
			return true
		}
	}
	return false
}

