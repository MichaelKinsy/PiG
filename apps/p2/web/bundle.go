// Package web is p2's browser client as Pi ships it (D471): the web bundle Pi's `buildWebBundle` makes of the vendored
// sources (upstream/, upstream-root/; build/ runs the same esbuild with the same options over them) embedded in the binary,
// and the installable app's public files. Nothing builds at run time.
package web

import (
	"embed"
	"encoding/json"
	"fmt"
	"io/fs"
	"sync"
)

//go:embed all:dist
var distFiles embed.FS

//go:embed upstream/public
var publicFiles embed.FS

// BundlePath is where the page loads the web bundle's files from (`WEB_BUNDLE_PATH`).
const BundlePath = "/__p2_web/"

// ManifestPath is the current web bundle manifest; its files remain under BundlePath (`WEB_MANIFEST_PATH`).
const ManifestPath = "/__p2_web"

// File is one file of the bundle: its Content-Type, size and content. The content is read from the embedded files when first
// asked for and kept: a server nobody loads the page from holds none of the bundle (about 9 MB with the source maps), and a
// source map nobody opens is never read.
type File struct {
	Type string
	// Size is the content's length in bytes.
	Size int

	files fs.FS
	path  string
	once  sync.Once
	body  []byte
}

// Body is the file's content (read once, shared: never modify it). An embedded file always reads; if it somehow does not, the
// result is empty.
func (f *File) Body() []byte {
	f.once.Do(func() { f.body, _ = fs.ReadFile(f.files, f.path) })
	return f.body
}

// NewFile is a bundle file with content in hand (tests build bundles by hand).
func NewFile(contentType string, body []byte) *File {
	f := &File{Type: contentType, Size: len(body)}
	f.once.Do(func() { f.body = body })
	return f
}

// Bundle is the web bundle: every file named by its content, so a page can cache it forever (`WebBundle`).
type Bundle struct {
	// Version is a hash over the names of all files, which carry their own content hashes.
	Version string
	// Files are by file name (`app-<hash>.js`), served under BundlePath.
	Files map[string]*File
	// Script is the entry script and Style its stylesheet ("" for none), as file names.
	Script string
	Style  string
	// Plugins are the plugins whose web facets the bundle holds, alphabetical.
	Plugins []string
	// Brand is how the page names the app and colours its first paint (Pi's, unless the bundle was branded).
	Brand Brand
	// Public are the bundle's own versions of public files (the brand's icons and manifest), by path under public/.
	Public map[string][]byte
	// UpstreamVersion is the version of the unbranded bundle (Pi's own) this one was branded from; "" when not branded.
	UpstreamVersion string
}

// Brand is the identity of the page itself (the part of the brand the Go server writes; the rest is in the bundle's CSS and
// sources): the name in the title and the home-screen title, and the colours of the first paint and of the browser chrome.
type Brand struct {
	Name  string
	Light string
	Dark  string
}

// UpstreamBrand is Pi's own (web.ts).
var UpstreamBrand = Brand{Name: "Pi", Light: "#fbfaf8", Dark: "#151413"}

// Manifest is what pages poll (`WebManifest`): the bundle's version and its files' addresses. Style is null for none.
type Manifest struct {
	Version string  `json:"version"`
	Script  string  `json:"script"`
	Style   *string `json:"style"`
}

// Manifest is the bundle's manifest (`webManifest`).
func (b *Bundle) Manifest() Manifest {
	manifest := Manifest{Version: b.Version, Script: BundlePath + b.Script}
	if b.Style != "" {
		style := BundlePath + b.Style
		manifest.Style = &style
	}
	return manifest
}

type bundleJSON struct {
	Version string   `json:"version"`
	Script  string   `json:"script"`
	Style   *string  `json:"style"`
	Plugins []string `json:"plugins"`
	Files   []struct {
		Name string `json:"name"`
		Type string `json:"type"`
	} `json:"files"`
	Brand *struct {
		Name            string                       `json:"name"`
		ThemeColor      struct{ Light, Dark string } `json:"themeColor"`
		UpstreamVersion string                       `json:"upstreamVersion"`
		Public          []string                     `json:"public"`
	} `json:"brand"`
}

var (
	loadOnce sync.Once
	loaded   *Bundle
	loadErr  error
)

// Embedded is the web bundle built into the binary (`dist/`, generated by build/assemble.sh).
func Embedded() (*Bundle, error) {
	loadOnce.Do(func() { loaded, loadErr = load(distFiles, "dist") })
	return loaded, loadErr
}

func load(files fs.FS, dir string) (*Bundle, error) {
	raw, err := fs.ReadFile(files, dir+"/bundle.json")
	if err != nil {
		return nil, fmt.Errorf("web bundle: %w", err)
	}
	var described bundleJSON
	if err := json.Unmarshal(raw, &described); err != nil {
		return nil, fmt.Errorf("web bundle: bundle.json: %w", err)
	}
	bundle := &Bundle{Version: described.Version, Script: described.Script, Plugins: described.Plugins, Files: make(map[string]*File, len(described.Files))}
	if described.Style != nil {
		bundle.Style = *described.Style
	}
	for _, file := range described.Files {
		info, err := fs.Stat(files, dir+"/"+file.Name)
		if err != nil {
			return nil, fmt.Errorf("web bundle: %w", err)
		}
		bundle.Files[file.Name] = &File{Type: file.Type, Size: int(info.Size()), files: files, path: dir + "/" + file.Name}
	}
	bundle.Brand = UpstreamBrand
	if described.Brand != nil {
		bundle.Brand = Brand{Name: described.Brand.Name, Light: described.Brand.ThemeColor.Light, Dark: described.Brand.ThemeColor.Dark}
		bundle.UpstreamVersion = described.Brand.UpstreamVersion
		bundle.Public = make(map[string][]byte, len(described.Brand.Public))
		for _, name := range described.Brand.Public {
			body, err := fs.ReadFile(files, dir+"/public/"+name)
			if err != nil {
				return nil, fmt.Errorf("web bundle: %w", err)
			}
			bundle.Public[name] = body
		}
	}
	if _, ok := bundle.Files[bundle.Script]; !ok {
		return nil, fmt.Errorf("web bundle: no entry script %q", bundle.Script)
	}
	return bundle, nil
}

// PublicFile is a file of `public/` the page and the installed app load.
type PublicFile struct {
	Type string
	// File is the path under public/.
	File string
	// Cache is the Cache-Control value ("" for the default, a day).
	Cache string
}

// publicFileTable is `PUBLIC_FILES` of src/hosts/web.ts: by request path. They hold nothing private.
var publicFileTable = map[string]PublicFile{
	"/manifest.webmanifest":             {Type: "application/manifest+json", File: "manifest.webmanifest"},
	"/icons/favicon.svg":                {Type: "image/svg+xml", File: "icons/favicon.svg"},
	"/icons/apple-touch-icon.png":       {Type: "image/png", File: "icons/apple-touch-icon.png"},
	"/icons/icon-192.png":               {Type: "image/png", File: "icons/icon-192.png"},
	"/icons/icon-512.png":               {Type: "image/png", File: "icons/icon-512.png"},
	"/apple-touch-icon.png":             {Type: "image/png", File: "icons/apple-touch-icon.png"},
	"/apple-touch-icon-precomposed.png": {Type: "image/png", File: "icons/apple-touch-icon.png"},
	"/sw.js":                            {Type: "text/javascript; charset=utf-8", File: "sw.js", Cache: "no-cache"},
}

// LookupPublicFile is path's public file, if it is one.
func LookupPublicFile(path string) (PublicFile, bool) {
	file, ok := publicFileTable[path]
	return file, ok
}

// ReadPublicFile is the content of a public file: the bundle's own version (the brand's), else Pi's.
func (b *Bundle) ReadPublicFile(file PublicFile) ([]byte, error) {
	if body, ok := b.Public[file.File]; ok {
		return body, nil
	}
	return fs.ReadFile(publicFiles, "upstream/public/"+file.File)
}
