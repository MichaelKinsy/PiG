package main

import (
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

// The README porting block explains the numbers beside the README badges. It
// is generated with the AGENTS.md block so the two cannot disagree:
//
//	<!-- BEGIN PORTING -->
//	...
//	<!-- END PORTING -->
const (
	portingBeginMarker = "<!-- BEGIN PORTING -->"
	portingEndMarker   = "<!-- END PORTING -->"
)

// check-port-map-drift.py --reconcile writes this note into the mapping column
// of each upstream file it adds as not started.
var newUpstreamNote = regexp.MustCompile(`new upstream by ([0-9][0-9A-Za-z.+-]*)`)

// replaceBetweenMarkers swaps the text between begin and end for block.
func replaceBetweenMarkers(src, begin, end, block string) (string, error) {
	beginIdx := strings.Index(src, begin)
	endIdx := strings.Index(src, end)
	if beginIdx < 0 || endIdx < 0 || endIdx < beginIdx {
		return "", fmt.Errorf("missing %q ... %q markers", begin, end)
	}
	return src[:beginIdx+len(begin)] + "\n" + block + "\n" + src[endIdx:], nil
}

func patchFileBlock(path, begin, end, block string) error {
	body, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	out, err := replaceBetweenMarkers(string(body), begin, end, block)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if out == string(body) {
		return nil
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

// upstreamPackages lists the Pi packages PORT_MAP.md maps, in order.
func upstreamPackages(entries []portMapEntry) []string {
	seen := map[string]bool{}
	var names []string
	for _, e := range entries {
		parts := strings.SplitN(e.UpstreamPath, "/", 3)
		if len(parts) < 3 || parts[0] != "packages" || seen[parts[1]] {
			continue
		}
		seen[parts[1]] = true
		names = append(names, parts[1])
	}
	sort.Strings(names)
	return names
}

// newUpstreamRows counts not-started rows that reconciliation added for the
// pinned Pi version.
func newUpstreamRows(entries []portMapEntry, pinned string) int {
	n := 0
	for _, e := range entries {
		if m := newUpstreamNote.FindStringSubmatch(e.PigPath); e.Status == "⬜" && m != nil && m[1] == pinned {
			n++
		}
	}
	return n
}

func joinList(items []string) string {
	quoted := make([]string, len(items))
	for i, item := range items {
		quoted[i] = "`" + item + "`"
	}
	switch len(quoted) {
	case 0:
		return ""
	case 1:
		return quoted[0]
	case 2:
		return quoted[0] + " and " + quoted[1]
	}
	return strings.Join(quoted[:len(quoted)-1], ", ") + ", and " + quoted[len(quoted)-1]
}

// remainderClause names the intended-portable rows that are not ported yet.
func (s statusStats) remainderClause(newRows int, pinned string) string {
	var parts []string
	if s.Partial > 0 {
		parts = append(parts, fmt.Sprintf("%d are partial", s.Partial))
	}
	if s.Broken > 0 {
		parts = append(parts, fmt.Sprintf("%d are broken", s.Broken))
	}
	if s.NotStarted > 0 {
		parts = append(parts, fmt.Sprintf("%d are not started", s.NotStarted))
	}
	if len(parts) == 0 {
		return ""
	}
	clause := fmt.Sprintf(" Of the other %d, %s.", s.intendedPortable()-s.Ported, strings.Join(parts, " and "))
	switch {
	case newRows == s.NotStarted && newRows > 0:
		clause += fmt.Sprintf(" The not-started rows are files new in Pi %s that PiG has not ported yet.", pinned)
	case newRows > 0:
		clause += fmt.Sprintf(" Not started includes %d files new in Pi %s that PiG has not ported yet.", newRows, pinned)
	}
	return clause
}

// portingBlock renders the README lines that explain the porting numbers and
// the parity coverage badge.
func portingBlock(entries []portMapEntry, s statusStats, pinned string) string {
	porting := fmt.Sprintf("**Porting:** %d of %d intended-portable upstream files are ported (%.1f%%). "+
		"The %d are the [`PORT_MAP.md`](PORT_MAP.md) rows for Pi's %s packages, excluding %d `n/a` and %d deferred rows.%s",
		s.Ported, s.intendedPortable(), s.portingPercentage(),
		s.intendedPortable(), joinList(upstreamPackages(entries)), s.NA, s.Deferred,
		s.remainderClause(newUpstreamRows(entries, pinned), pinned))
	badge := fmt.Sprintf("**Behavioral evidence badge:** %d of the %d ported files (%.1f%%) have a behavioral paired scenario or reviewed mutation-proven unit test. "+
		"The badge counts evidence mappings, not passing runs; [`parity/coverage.md`](parity/coverage.md) shows the last recorded run.",
		s.Behavioral, s.Ported, s.behavioralPercentage())
	return "<!-- Generated by `make coverage`. Do not hand-edit. -->\n" + porting + "\n\n" + badge
}
