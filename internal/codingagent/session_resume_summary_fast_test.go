// The picker's member walk folds every line into the summary exactly as decoding the whole line does: the same error, count, name, last
// activity, first message and texts after each line of the parity scenarios' session files, a generated long session and lines whose members
// only the decoder reads exactly.
func TestResumePickerMemberWalkMatchesTheWholeDecode(t *testing.T) {
	paths, _ := filepath.Glob("../../test/parity/scenarios/*/testdata/*/sessions/*.jsonl")
	more, _ := filepath.Glob("../../test/parity/scenarios/*/testdata/sessions/*.jsonl")
	var lines [][]byte
	for _, path := range append(paths, more...) {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		lines = append(lines, bytes.Split(data, []byte("\n"))...)
	}
	var generated bytes.Buffer
	if _, err := longsession.Generate(&generated, longsession.Options{Tokens: 100000, Window: 200000, Seed: 9, Cwd: "/project"}); err != nil {
		t.Fatal(err)
	}
	lines = append(lines, bytes.Split(generated.Bytes(), []byte("\n"))...)
	head := `{"type":"message","id":"a","parentId":null,"timestamp":"2026-01-01T00:00:00.000Z",`
	for _, extra := range []string{
		head + `"message":{"role":"user","content":"plain","timestamp":5}}`,
		head + `"message":{"role":"user","content":[{"type":"text","text":"a"},{"type":"toolCall","arguments":{"x":1e400}}],"timestamp":5}}`,
		head + `"message":{"role":"user","content":[{"type":"text","text":12.50},{"type":"text","text":null},{"type":"text"},{"type":"text","text":[1,null,"b"]},{"type":"text","text":{"o":1}}]}}`,
		head + `"message":{"role":"user","content":[null]}}`,
		head + `"message":{"role":"user","content":[1,"s",[],{"type":"image"}]}}`,
		head + `"message":{"role":"user","content":null}}`,
		head + `"message":{"role":"user","content":7}}`,
		head + `"message":{"role":"user","content":{"type":"text"}}}`,
		head + `"message":{"role":"user"}}`,
		head + `"message":{"role":"us\u0065r","content":"escaped role"}}`,
		head + `"message":{"Role":"user","content":"folded key"}}`,
		head + `"message":{"role":"user","role":"assistant","content":"repeated role"}}`,
		head + `"message":{"role":"user","role":"toolResult","content":"repeated role, the last no user"}}`,
		head + `"message":{"role":"assistant","content":[{"type":"text","type":"thinking","text":"repeated type"}]}}`,
		head + `"message":{"role":"user","content":[{"t\u0079pe":"text","text":"escaped key"}]}}`,
		head + `"message":{"role":"user","content":[{"type":"te\u0078t","text":"escaped type"}]}}`,
		head + `"message":{"role":"user","content":"string timestamp","timestamp":"5"}}`,
		head + `"message":{"role":"user","content":"huge timestamp","timestamp":1e400}}`,
		head + `"message":null}`,
		head + `"message":"string"}`,
		`{"type":"message","id":"a","parentId":null,"message":{"role":"user","content":"no entry timestamp"}}`,
		`{"type":"message","id":"a","timestamp":null,"message":{"role":"user","content":"null entry timestamp"}}`,
		`{"type":"message","id":"a","timestamp":17e2,"message":{"role":"user","content":"number entry timestamp"}}`,
		`{"type":"message","type":"session_info","name":"repeated type"}`,
		`{"type":"session_info","name":"  named  "}`,
		`{"type":"session_info","name":3}`,
		`{"Type":"message","message":{"role":"user","content":"folded type"}}`,
		`{"type":"messag\u0065","message":{"role":"user","content":"escaped type"}}`,
		`{"type":"model_change","provider":"p"}`,
		`{"type":1}`,
		`{}`,
		`[1,2]`,
		`"string"`,
		`0`,
		`null`,
		`{"type":"message",`,
		`  {"type":"message","message":{"role":"user","content":"spaced"}}  `,
		head + `"message":{"role":"user","content":"` + "\xff" + `invalid utf-8"}}`,
	} {
		lines = append(lines, []byte(extra))
	}
	fast, whole := newSummaryPartial(true), newSummaryPartial(true)
	var fastName, wholeName bool
	walked := 0
	for _, line := range lines {
		if len(bytes.TrimSpace(line)) == 0 {
			continue
		}
		gotErr := fast.feed(line, true, &fastName)
		wantErr := whole.feedDecoded(line, true, &wholeName)
		if done, _ := (&summaryPartial{noHeader: true, last: math.NaN()}).feedMessageLine(line); done {
			walked++
		}
		if !errors.Is(gotErr, wantErr) || fastName != wholeName || !sameSummary(fast, whole) {
			t.Fatalf("after %s:\nwalk  %v %+v\nwhole %v %+v", line, gotErr, *fast, wantErr, *whole)
		}
		if gotErr != nil {
			fast, whole = newSummaryPartial(true), newSummaryPartial(true)
		}
	}
	t.Logf("%d lines, %d walked", len(lines), walked)
	if walked == 0 || walked == len(lines) {
		t.Fatalf("%d of %d lines walked: the corpus no longer covers both paths", walked, len(lines))
	}
}

func sameSummary(a, b *summaryPartial) bool {
	sameLast := a.last == b.last || math.IsNaN(a.last) && math.IsNaN(b.last)
	return sameLast && a.count == b.count && a.name == b.name && a.first == b.first && reflect.DeepEqual(a.texts, b.texts)
}
