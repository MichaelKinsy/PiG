package codingagent

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"

	"github.com/MichaelKinsy/PiG/internal/jsonstringify"
	"github.com/MichaelKinsy/PiG/test/longsession"
)

// replaceJSONField's splice of a canonical record writes what the member-by-member rewrite and Canonicalize write, over every record of the
// parity scenarios' session files, a generated long session and records with repeated, escaped, integer-like and missing members.
func TestSpliceCanonicalMemberMatchesTheRewrite(t *testing.T) {
	paths, _ := filepath.Glob("../../test/parity/scenarios/*/testdata/*/sessions/*.jsonl")
	more, _ := filepath.Glob("../../test/parity/scenarios/*/testdata/sessions/*.jsonl")
	var lines [][]byte
	for _, path := range append(paths, more...) {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		lines = append(lines, bytes.Split(data, []byte("\n"))...)
	}
	var generated bytes.Buffer
	if _, err := longsession.Generate(&generated, longsession.Options{Tokens: 100000, Window: 200000, Seed: 5, Cwd: "/project"}); err != nil {
		t.Fatal(err)
	}
	lines = append(lines, bytes.Split(generated.Bytes(), []byte("\n"))...)
	for _, extra := range []string{
		`{"type":"message","id":"a","parentId":"p","parentId":"q","timestamp":"t"}`,
		`{"type":"message","id":"a","parent\u0049d":"p","timestamp":"t"}`,
		`{"type":"message","7":"x","id":"a","parentId":"p","timestamp":"t"}`,
		`{"type":"message","id":"a","timestamp":"t"}`,
		`{"type":"message","id":"a","parentId":null,"timestamp":"t","message":{"parentId":"inner"}}`,
		`{"type":"compaction","id":"c","parentId":"p","timestamp":"t","summary":"s","firstKeptEntryId":"k","tokensBefore":1,"fromHook":false}`,
		`{ "type":"message","id":"a","parentId":"p"}`,
		`{"type":"message","id":"a","parentId":1.0,"timestamp":"t"}`,
		`[1,2]`,
		`{}`,
	} {
		lines = append(lines, []byte(extra))
	}
	parent := "0b9a7059"
	odd := "a\"b\u2028c"
	values := []struct {
		field string
		value any
	}{{"parentId", (*string)(nil)}, {"parentId", &parent}, {"parentId", &odd}, {"firstKeptEntryId", "k2"}, {"version", 3}}
	spliced, records := 0, 0
	for _, line := range lines {
		line = bytes.TrimSpace(line)
		if len(line) == 0 {
			continue
		}
		records++
		for _, v := range values {
			got, gotErr := replaceJSONField(line, v.field, v.value)
			rewritten, wantErr := rewriteMemberJSONField(line, v.field, v.value, false)
			var want []byte
			if wantErr == nil {
				want, wantErr = jsonstringify.Canonicalize(rewritten)
			}
			if (gotErr == nil) != (wantErr == nil) || !bytes.Equal(got, want) {
				t.Fatalf("replaceJSONField(%s, %s, %v) = %s (%v), the rewrite writes %s (%v)", line, v.field, v.value, got, gotErr, want, wantErr)
			}
			if _, ok, _ := spliceCanonicalMember(line, v.field, v.value); ok {
				spliced++
			}
		}
	}
	t.Logf("%d records, %d rewrites spliced", records, spliced)
	if spliced == 0 || spliced == records*len(values) {
		t.Fatalf("%d of %d rewrites spliced: the corpus no longer covers both paths", spliced, records*len(values))
	}
}
