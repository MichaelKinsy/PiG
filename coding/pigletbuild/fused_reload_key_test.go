package pigletbuild

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/MichaelKinsy/PiG/coding/extension/host/subprocess"
	piglet "github.com/MichaelKinsy/PiG/coding/piglet"
)

// stockFuseRegistry is the registry a build generated for one fused member before `build.fusedReload` existed.
const stockFuseRegistry = "// Code generated by pig piglet build. DO NOT EDIT.\npackage fusepack\n\nimport (\n\text_trace \"example.com/extensions/trace\"\n)\n\nfunc init() {\n\tregisterFactory(\"trace\", ext_trace.Extension)\n}\n"

func fusedReloadFixture(t *testing.T) []fusedEntry {
	t.Helper()
	root := t.TempDir()
	for name, content := range map[string]string{
		"go.mod":       "module example.com/extensions/trace\n\ngo 1.26\n",
		"extension.go": "package trace\n",
	} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return []fusedEntry{{Name: "trace", Pkg: "ext_trace", Package: "example.com/extensions/trace", Factory: "Extension", Root: root}}
}

// A Piglet without `build.fusedReload` bakes no source digest: the generated registry is byte-equal to the one a build wrote before the
// key existed, so the Binary has nothing to compare and loads its fused members as it did.
func TestFuseRegistryWithoutFusedReloadIsUnchanged(t *testing.T) {
	for name, p := range map[string]*piglet.Piglet{
		"no build section": {Name: "x"},
		"build without it": {Name: "x", Build: &piglet.BuildSpec{ExtensionRealization: "fused"}},
	} {
		t.Run(name, func(t *testing.T) {
			entries := fusedReloadFixture(t)
			if err := bakeFusedSourceDigests(p, entries); err != nil {
				t.Fatal(err)
			}
			if entries[0].SourceDigest != "" {
				t.Fatalf("baked %q without the key", entries[0].SourceDigest)
			}
			if got := renderFuseRegistry(entries); got != stockFuseRegistry {
				t.Fatalf("registry without build.fusedReload:\n%s\nwant byte-equal:\n%s", got, stockFuseRegistry)
			}
		})
	}
}

// `build.fusedReload: source` bakes, for each fused member, the digest the host computes of the same source.
func TestFuseRegistryWithFusedReloadSourceBakesTheSourceDigest(t *testing.T) {
	entries := fusedReloadFixture(t)
	if err := bakeFusedSourceDigests(&piglet.Piglet{Name: "x", Build: &piglet.BuildSpec{FusedReload: piglet.FusedReloadSource}}, entries); err != nil {
		t.Fatal(err)
	}
	want, err := subprocess.FusedSourceDigest(entries[0].Root)
	if err != nil || want == "" || entries[0].SourceDigest != want {
		t.Fatalf("baked %q, host digest %q, %v", entries[0].SourceDigest, want, err)
	}
	wantRegistry := stockFuseRegistry[:len(stockFuseRegistry)-2] + "\tregisterSource(\"trace\", \"" + want + "\")\n}\n"
	if got := renderFuseRegistry(entries); got != wantRegistry {
		t.Fatalf("registry:\n%s\nwant:\n%s", got, wantRegistry)
	}
	entries[0].Root = filepath.Join(entries[0].Root, "missing")
	if err := bakeFusedSourceDigests(&piglet.Piglet{Name: "x", Build: &piglet.BuildSpec{FusedReload: piglet.FusedReloadSource}}, entries); err == nil {
		t.Fatal("a member whose source cannot be read was baked")
	}
}
