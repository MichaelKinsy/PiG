package piglet

import (
	"strings"

	"github.com/MichaelKinsy/PiG/coding/extension"
)

// The tool scope rule table of the docs (internal/pigdocs/content/piglets.md and mcp.md) is computed here from the same
// code that scopes the Session's tool registry: each row builds a Piglet or a `--tools` filter, asks it about a fixed set of
// probe tools and words the answers. TestToolScopeTableMatchesDocs keeps the docs equal to this output.

// ToolScopeTableStart and ToolScopeTableEnd bracket the table in the docs.
const (
	ToolScopeTableStart = "<!-- tool-scope-table:start (generated by coding/piglet/scope_table.go; do not edit) -->"
	ToolScopeTableEnd   = "<!-- tool-scope-table:end -->"
)

var (
	probeServerTools   = []string{"mcp__docs__a", "mcp__docs__b"}
	probeResourceTools = []string{extension.ReadMcpResourceTool}
	probeReachTools    = []string{"codemode", "tool_search"}
)

type scopeRow struct {
	name string
	// keeps reports whether the row keeps a probe tool in the registry.
	keeps func(extension.ToolInfo) bool
}

func pigletRow(name string, p *Piglet) scopeRow {
	owner := func(tool extension.ToolInfo) string {
		switch tool.Name {
		case "codemode":
			return "codemode"
		case "tool_search":
			return "tool-search"
		}
		return ""
	}
	return scopeRow{name: name, keeps: CompileToolScope(p, owner).Keeps}
}

func filterRow(name string, allowed, excluded []string) scopeRow {
	set := func(names []string) map[string]struct{} {
		if names == nil {
			return nil
		}
		out := make(map[string]struct{}, len(names))
		for _, n := range names {
			out[n] = struct{}{}
		}
		return out
	}
	filter := extension.NewToolFilter(set(allowed), set(excluded))
	return scopeRow{name: name, keeps: filter.AllowsTool}
}

func scopeRows() []scopeRow {
	adapterList := []string{"mcp__docs__a"}
	return []scopeRow{
		pigletRow("Piglet with no `extensions:` section", &Piglet{}),
		pigletRow("Piglet with `extensions:` but without `pig-mcp-adapter`", &Piglet{Extensions: []ExtensionEntry{{Name: "other"}}}),
		pigletRow("Piglet with `pig-mcp-adapter` and no `tools:`", &Piglet{Extensions: []ExtensionEntry{{Name: MCPAdapterExtensionName}}}),
		pigletRow("Piglet with `pig-mcp-adapter` and `tools: [mcp__docs__a]`", &Piglet{Extensions: []ExtensionEntry{{Name: MCPAdapterExtensionName, Tools: &adapterList}}}),
		pigletRow("Piglet run with `-e builtin:codemode` and `-e builtin:tool-search`, without `pig-mcp-adapter`", &Piglet{Extensions: []ExtensionEntry{{Name: "other"}}}),
		filterRow("Stock `--tools read`", []string{"read"}, nil),
		filterRow("Stock `--tools read,codemode,tool_search,mcp__docs__a`", []string{"read", "codemode", "tool_search", "mcp__docs__a"}, nil),
		filterRow("Stock `--exclude-tools mcp__docs__b`", nil, []string{"mcp__docs__b"}),
		filterRow("Stock `--no-tools`", []string{}, nil),
	}
}

// probe builds the info of a probe tool the way the Session reports it.
func probe(name string) extension.ToolInfo {
	info := extension.ToolInfo{Name: name}
	if strings.HasPrefix(name, "mcp__docs__") {
		info.Namespace = &extension.ToolNamespace{Name: extension.McpNamespace("docs")}
	}
	return info
}

func verdict(row scopeRow, names []string) string {
	kept := 0
	for _, name := range names {
		if row.keeps(probe(name)) {
			kept++
		}
	}
	switch {
	case kept == len(names):
		return "kept"
	case kept == 0:
		return "removed"
	}
	return "only the tools it names"
}

// ToolScopeTableMarkdown renders the tool scope rule table, one row per case, from the code that scopes the registry.
func ToolScopeTableMarkdown() string {
	var out strings.Builder
	out.WriteString(ToolScopeTableStart + "\n\n")
	out.WriteString("| Case | MCP server tools | MCP resource tools | `codemode` and `tool_search` |\n|---|---|---|---|\n")
	for _, row := range scopeRows() {
		out.WriteString("| " + row.name + " | " + verdict(row, probeServerTools) + " | " + verdict(row, probeResourceTools) + " | " + verdict(row, probeReachTools) + " |\n")
	}
	out.WriteString("\n" + ToolScopeTableEnd)
	return out.String()
}
