// Generates property_data.go: the Unicode data Go's unicode package cannot supply, taken from this Node's own tables (V8 uses ICU).
// Run with plain Node 24 from this directory: node gen/property_data.mjs
import { writeFileSync } from "node:fs";
import { discoverScriptAliases, scriptLongNames } from "./names.mjs";
import { formatRanges, rangesOf, subtract, withoutSurrogates } from "./unicode.mjs";

// Properties of ECMA-262 with no table in Go's unicode package and no derivation from the tables it has.
const generated = [
  "Bidi_Mirrored", "Case_Ignorable", "Changes_When_Casefolded", "Changes_When_Casemapped", "Changes_When_Lowercased",
  "Changes_When_NFKC_Casefolded", "Changes_When_Titlecased", "Changes_When_Uppercased", "Emoji", "Emoji_Component",
  "Emoji_Modifier", "Emoji_Modifier_Base", "Emoji_Presentation", "Extended_Pictographic", "XID_Continue", "XID_Start",
];

function stringLiteral(text) {
  const chunks = text.match(/.{1,96}/g) ?? [""];
  return chunks.map((c) => JSON.stringify(c)).join(" +\n\t\t");
}

function mapLiteral(name, entries) {
  const lines = entries.map(([k, v]) => `\t\t${JSON.stringify(k)}: ${stringLiteral(v)},`);
  return `var ${name} = lazyTable(func() map[string]string {\n\treturn map[string]string{\n${lines.join("\n")}\n\t}\n})\n`;
}

const { aliases } = discoverScriptAliases();
const aliasEntries = [...aliases].filter(([code, name]) => code !== name).sort(([a], [b]) => a.localeCompare(b));
const propertyEntries = generated.map((name) => [name, formatRanges(withoutSurrogates(rangesOf(name)))]);
const added = [];
const removed = [];
for (const name of scriptLongNames) {
  const sc = withoutSurrogates(rangesOf(`Script=${name}`) ?? []);
  const scx = withoutSurrogates(rangesOf(`Script_Extensions=${name}`) ?? []);
  const plus = subtract(scx, sc);
  const minus = subtract(sc, scx);
  if (plus.length) added.push([name, formatRanges(plus)]);
  if (minus.length) removed.push([name, formatRanges(minus)]);
}

// multiCharUppercase lists the code units whose upper case is not exactly one code unit; Canonicalize without the u flag leaves them alone.
const multi = [];
for (let c = 0; c <= 0xffff; c++) {
  if (String.fromCharCode(c).toUpperCase().length !== 1) {
    if (multi.length && multi[multi.length - 1] === c - 1) multi[multi.length - 1] = c;
    else multi.push(c, c);
  }
}

const out = `// Code generated by gen/property_data.mjs from Node ${process.versions.node} (V8 ${process.versions.v8}, Unicode ${process.versions.unicode}); DO NOT EDIT.

package ecmaregex

// scriptAliases maps the ISO 15924 codes and other short names V8 accepts for Script, sc, Script_Extensions and scx to the long script name.
${mapLiteral("scriptAliases", aliasEntries)}
// scriptExtensionsAdded lists, per long script name, the code points whose Script_Extensions contain the script although their Script differs; scriptExtensionsRemoved lists the code points of the script whose Script_Extensions do not contain it. Both are hex range lists.
${mapLiteral("scriptExtensionsAdded", added)}
${mapLiteral("scriptExtensionsRemoved", removed)}
// generatedProperties holds, per long property name, the hex range list of a binary property that neither Go's tables nor a derivation from them provide.
${mapLiteral("generatedProperties", propertyEntries)}
// multiCharUppercase is the hex range list of the code units whose upper case is several code units.
var multiCharUppercase = ${stringLiteral(formatRanges(multi))}
`;
writeFileSync(new URL("../property_data.go", import.meta.url), out);
console.log(`aliases=${aliasEntries.length} added=${added.length} removed=${removed.length} bytes=${out.length}`);
