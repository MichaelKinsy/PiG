"""Generate edit tasks by mutating real Go files, after the harness benchmark in oh-my-pi.

Each task takes one file from a corpus, applies one mechanical bug whose inverse
is known (operator inversion, boolean flip, off-by-one, logic swap, removed
guard), and describes it in plain English. A run passes when the file's gofmt
output hashes to the original's, so any fix that restores the code counts,
whatever its whitespace. Generation is seeded and reproducible.
"""
import hashlib
import json
import os
import random
import re
import shutil
import subprocess
import tempfile

from . import registry

FUNC = re.compile(r"^func (?:\([^)]*\) )?(\w+)")
PLAIN = re.compile(r'^[^"`/]*$')  # no strings, runes, or comments on the line


def _swap(old, new, desc, hint):
    def find(lines, i):
        line = lines[i]
        if PLAIN.match(line) and line.count(old) == 1 and not line.lstrip().startswith("func "):
            return [line.replace(old, new)], 1, desc, hint
    return find


def _drop_guard(lines, i):
    if i + 2 < len(lines) and re.match(r"^\s*if .+ \{$", lines[i]) and re.match(r"^\s*return\b", lines[i + 1]) and re.match(r"^\s*\}$", lines[i + 2]) and PLAIN.match(lines[i]):
        return [], 3, "A guard clause (early return) was removed.", "Restore the missing guard clause (if statement with early return)."


KINDS = {
    "invert-equality": _swap(" == ", " != ", "A comparison operator was inverted.", "Restore the original comparison."),
    "invert-inequality": _swap(" != ", " == ", "A comparison operator was inverted.", "Restore the original comparison."),
    "flip-boolean": _swap("return true", "return false", "A boolean literal was flipped.", "Restore the original boolean value."),
    "off-by-one": _swap(" < len(", " <= len(", "An off-by-one error was introduced in a bound.", "Restore the original bound."),
    "swap-logic": _swap(" && ", " || ", "A logical operator was swapped.", "Restore the original logical operator."),
    "drop-guard": _drop_guard,
}


def gofmt(text):
    return subprocess.run(["gofmt"], input=text, capture_output=True, text=True, check=True).stdout


def candidates(path):
    lines = open(path).read().split("\n")
    func = None
    for i, line in enumerate(lines):
        if (m := FUNC.match(line)):
            func = m.group(1)
        if func is None:
            continue
        for kind, find in KINDS.items():
            if (hit := find(lines, i)):
                yield kind, i, func, hit


def corpus_files(roots):
    for root in roots:
        for base, dirs, files in os.walk(os.path.join(registry.REPO_ROOT, root)):
            dirs[:] = [d for d in dirs if d != "testdata"]
            for name in sorted(files):
                path = os.path.join(base, name)
                if name.endswith(".go") and not name.endswith("_test.go") and "Code generated" not in open(path).read(2000):
                    yield path


def generate(out, count, seed, roots):
    """Write count tasks to out and return their ids."""
    if not shutil.which("gofmt"):
        raise SystemExit("mutate: gofmt not found; run make setup")
    rng = random.Random(seed)
    pool = [(path, *c) for path in corpus_files(roots) for c in candidates(path)]
    rng.shuffle(pool)
    shutil.rmtree(out, ignore_errors=True)
    ids, used = [], set()
    for path, kind, i, func, (replacement, span, desc, hint) in pool:
        if len(ids) == count:
            break
        if (path, kind) in used:
            continue
        original = open(path).read()
        lines = original.split("\n")
        mutated = "\n".join(lines[:i] + replacement + lines[i + span:])
        try:
            if gofmt(mutated) == gofmt(original):
                continue
        except subprocess.CalledProcessError:
            continue
        used.add((path, kind))
        name = os.path.basename(path)
        tid = f"{kind}-{name[:-3]}-{i + 1}"
        os.makedirs(os.path.join(out, tid, "files"))
        with open(os.path.join(out, tid, "files", name), "w") as f:
            f.write(mutated)
        digest = hashlib.sha256(gofmt(original).encode()).hexdigest()
        prompt = f"# Fix the bug in `{name}`\n\n{desc}\nThe issue is in the `{func}` function.\n{hint}"
        check = f"test \"$(gofmt {name} | sha256sum | cut -d' ' -f1)\" = {digest}"
        with open(os.path.join(out, tid, "task.toml"), "w") as f:
            f.write(f"# Generated by pigeval mutate --seed {seed} from {os.path.relpath(path, registry.REPO_ROOT)} line {i + 1}.\n")
            f.write(f"prompt = {json.dumps(prompt)}\ncheck = {json.dumps(check)}\ntimeout = 300\n")
        if not _verified(os.path.join(out, tid), name, original, check):
            shutil.rmtree(os.path.join(out, tid))
            continue
        ids.append(tid)
    return ids


def _verified(task_dir, name, original, check):
    """A task is kept only if its check fails on the mutated file and passes on the original."""
    files = os.path.join(task_dir, "files")
    if subprocess.run(["bash", "-c", check], cwd=files, capture_output=True).returncode == 0:
        return False
    with tempfile.TemporaryDirectory() as d:
        with open(os.path.join(d, name), "w") as f:
            f.write(original)
        return subprocess.run(["bash", "-c", check], cwd=d, capture_output=True).returncode == 0


def run(args):
    ids = generate(os.path.abspath(args.out), args.count, args.seed, args.roots.split(","))
    print(f"mutate: {len(ids)} tasks in {args.out} (seed {args.seed}); run them with make evals-live EVAL_TASKS_DIR={args.out} MODEL=...")
    return 0
