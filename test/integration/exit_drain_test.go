// Pi's drainInput(1000, 50) keeps the bytes a terminal sends after pig stops reading from reaching the shell. pig ends the
// wait on the reply to a DA1 query it writes after the disables (D622). These tests run the real binary and let the shell
// that follows it report what it receives: after pig exits the shell stops echo and canonical mode, reads what is queued on
// its terminal, and prints it with od.
//
// The terminal here is the test, and it behaves as one does: it handles pig's output in order, so what it sent before it
// handled the disables (in flight) precedes the reply to the DA1 query written after them, and what the user types after the
// reply follows it. Under tmux the terminal is tmux itself, which answers DA1 and handles the disables in order on the
// pane's terminal.

const keyboardPop = "\x1b[<u"

// exitDrainLaunch runs pig in dir and then the shell's probe of its own input. The markers are assembled by printf so the typed command line does not contain them.
func exitDrainLaunch(dir, bin string) string {
	return "cd " + shQuote(dir) + " && stty sane && PIG_HOME=" + shQuote(dir) + " PIG_OFFLINE=1 PIG_TEST_FAUX=1 PIG_QUIET_STARTUP=1 " + shQuote(bin) +
		" --model test-faux/faux-1 --no-extensions 2>/dev/null; printf 'PIG%s\\n' EXIT; stty -echo -icanon min 0 time 5; dd bs=256 count=1 2>/dev/null | od -An -c; printf 'SHELL%s\\n' END"
}

// shellReceived is what the shell printed between pig's exit and the end of its read, as od -c prints it with the spaces removed: empty when nothing reached it.
func shellReceived(t *testing.T, screen string) string {
	t.Helper()
	start := strings.LastIndex(screen, "PIGEXIT")
	end := strings.LastIndex(screen, "SHELLEND")
	if start < 0 || end < start {
		t.Fatalf("the shell never reported its input; screen:\n%q", screen)
	}
	return strings.Join(strings.Fields(screen[start+len("PIGEXIT"):end]), "")
}

func shQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// exitDrainTerminal is a terminal's behaviour around the exit.
type exitDrainTerminal struct {
	name string
	// fullscreen runs the alternate-screen renderer, which keeps mouse and focus reporting on until it stops; regular runs the main-screen renderer. Neither: the default mode.
	fullscreen, regular bool
	// kitty answers the Kitty flags query with flags that report key releases.
	kitty bool
	// withholdColors holds the DA1 reply of pig's terminal color query until the exit, where an earlier query's reply is still in flight.
	withholdColors bool
	// mouse sends a mouse motion report every 2 ms from the quit until the terminal handles the exit's disables.
	mouse bool
	// inFlight is what the terminal sends before it handles the disables: a held key's release, a modified key.
	inFlight string
	// replyDelay is how long after the exit's DA1 query the terminal's reply comes (a slow link).
	replyDelay time.Duration
	// typedAfter is what the user types after the terminal's reply to the exit's query.
	typedAfter string
	// want is set where typedAfter is: the shell must receive the typed bytes, as od prints them, and no terminal-generated byte.
}

// da1Reply answers DA1 and the colors query's DA1 alike.
const da1Reply = "\x1b[?62;22c"

func TestExitLeavesNoStrayBytesForTheShellOnAPlainPty(t *testing.T) {
	bin := buildBinary(t)
	for _, tc := range []exitDrainTerminal{
		{name: "default settings", inFlight: "\x1b[27;5;99~"},
		{name: "kitty protocol on", kitty: true, inFlight: "\x1b[99;5:3u\x1b[1;1:3A"},
		{name: "query in flight", withholdColors: true, inFlight: "\x1b[27;5;99~"},
		{name: "mouse moving during the exit", fullscreen: true, mouse: true, inFlight: "\x1b[I\x1b[O"},
		{name: "fullscreen with kitty and a query in flight", fullscreen: true, kitty: true, withholdColors: true, mouse: true, inFlight: "\x1b[99;5:3u\x1b[<35;10;5M"},
		{name: "slow link", kitty: true, inFlight: "\x1b[99;5:3u", replyDelay: 80 * time.Millisecond},
		{name: "very slow link", fullscreen: true, mouse: true, inFlight: "\x1b[I", replyDelay: 400 * time.Millisecond},
		{name: "regular renderer", regular: true, inFlight: "\x1b[27;5;99~"},
		{name: "regular renderer, kitty, slow link", regular: true, kitty: true, inFlight: "\x1b[99;5:3u", replyDelay: 80 * time.Millisecond},
		{name: "regular renderer, query in flight, type-ahead", regular: true, withholdColors: true, inFlight: "ab", typedAfter: "ls\r"},
		{name: "type-ahead after the reply", inFlight: "ab", typedAfter: "ls\r"},
		{name: "type-ahead after the reply under kitty", kitty: true, inFlight: "\x1b[99;5:3u", typedAfter: "ls\r"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			seedIntegrationSettings(t, dir)
			if mode := map[bool]string{tc.fullscreen: "fullscreen", tc.regular: "regular"}[true]; mode != "" {
				if err := os.WriteFile(filepath.Join(dir, "agent", "settings.json"), []byte(`{"tuiMode":"`+mode+`"}`), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			master, slave, err := openHangupPTY()
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = master.Close() }()
			cmd := exec.Command("sh", "-c", exitDrainLaunch(dir, bin))
			cmd.Stdin, cmd.Stdout, cmd.Stderr = slave, slave, slave
			cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true, Setctty: true, Ctty: 0}
			if err := cmd.Start(); err != nil {
				t.Fatal(err)
			}
			_ = slave.Close()
			defer func() { _ = cmd.Process.Kill(); _ = cmd.Wait() }()

			screen, took := driveExitDrainTerminal(t, master, tc)
			got := shellReceived(t, screen)
			if tc.typedAfter != "" {
				// The echo of a key typed once pig restored cooked mode may precede od's print of it.
				if !strings.Contains(got, "ls") || strings.Contains(got, "033") || strings.Contains(got, "ab") {
					t.Fatalf("the shell received %q after pig exited, want the type-ahead ls and no terminal-generated byte", got)
				}
			} else if got != "" {
				t.Fatalf("the shell received %q after pig exited, want nothing", got)
			}
			if tc.replyDelay > 0 && took < tc.replyDelay {
				t.Fatalf("pig exited %v after the quit, before the reply that took %v", took, tc.replyDelay)
			}
		})
	}
}

// driveExitDrainTerminal plays the terminal until the shell reports, and returns the screen and the time from the exit's DA1 query to the shell's report. It answers the startup queries, types /quit once the interface is up, and on the exit's DA1 query sends what tc says, in order.
func driveExitDrainTerminal(t *testing.T, master *os.File, tc exitDrainTerminal) (string, time.Duration) {
	t.Helper()
	var screen bytes.Buffer
	// The master is a blocking file: a goroutine reads it, so the loop below can act on time.
	chunks := make(chan []byte)
	done := make(chan struct{})
	defer close(done)
	go func() {
		for {
			chunk := make([]byte, 4096)
			n, err := master.Read(chunk)
			if n > 0 {
				select {
				case chunks <- chunk[:n]:
				case <-done:
					return
				}
			}
			if err != nil {
				close(chunks)
				return
			}
		}
	}()
	const colorsTail = "\x1b]4;15;?\x07\x1b[c"
	var kittyReplies, scanned, colorQueries, withheld int
	quit, sentQuit, exited := false, false, false
	var quitAt, lastMouse, queryAt time.Time
	// quitLen is the output length when /quit was typed; popAt is where the Kitty pop that the exit writes first lies after it.
	quitLen, popAt := 0, -1
	deadline := time.Now().Add(60 * time.Second)
	for time.Now().Before(deadline) {
		select {
		case chunk, ok := <-chunks:
			if !ok {
				t.Fatalf("the terminal closed before the shell reported; screen:\n%q", screen.String())
			}
			screen.Write(chunk)
		case <-time.After(2 * time.Millisecond):
		}
		text := screen.String()
		if tc.kitty && strings.Count(text, "\x1b[?u") > kittyReplies {
			kittyReplies++
			_, _ = master.WriteString("\x1b[?7u")
		}
		if sentQuit && popAt < 0 {
			if i := strings.Index(text[quitLen:], keyboardPop); i >= 0 {
				popAt = quitLen + i
			}
		}
		// Every DA1 query not yet answered, in the order written.
		for {
			i := strings.Index(text[scanned:], "\x1b[c")
			if i < 0 {
				break
			}
			at := scanned + i
			scanned = at + len("\x1b[c")
			switch {
			case popAt >= 0 && at > popAt:
				exited, queryAt = true, time.Now()
				// In order: the owed reply of the earlier query, what was in flight, then the reply to this query, then what the user typed.
				if withheld > 0 {
					_, _ = master.WriteString(strings.Repeat(da1Reply, withheld))
					withheld = 0
				}
				_, _ = master.WriteString(tc.inFlight)
				if tc.replyDelay > 0 {
					time.Sleep(tc.replyDelay)
				}
				_, _ = master.WriteString(da1Reply)
				if tc.typedAfter != "" {
					// The user types once the exit has settled (5 ms after the reply): it is queued for the shell, whether pig has restored cooked mode yet or not.
					time.Sleep(10 * time.Millisecond)
					_, _ = master.WriteString(tc.typedAfter)
				}
			case strings.HasSuffix(text[:scanned], colorsTail):
				colorQueries++
				if tc.withholdColors {
					withheld++
				} else {
					_, _ = master.WriteString(da1Reply)
				}
			default:
				_, _ = master.WriteString(da1Reply)
			}
		}
		if !quit && strings.Contains(text, interactiveReadyMarker) {
			quit, quitAt = true, time.Now().Add(300*time.Millisecond)
		}
		if quit && !sentQuit && time.Now().After(quitAt) {
			if tc.withholdColors && colorQueries == 0 {
				t.Fatalf("pig sent no terminal color query, so none is in flight at the exit; screen:\n%q", text)
			}
			sentQuit, quitLen = true, len(text)
			_, _ = master.WriteString("/quit\r")
		}
		if sentQuit && tc.mouse && !exited && time.Since(lastMouse) >= 2*time.Millisecond {
			lastMouse = time.Now()
			_, _ = master.WriteString("\x1b[<35;10;5M")
		}
		if strings.Contains(text, "SHELLEND") {
			if !exited {
				t.Fatalf("pig never wrote the exit's DA1 query; output after the quit:\n%q", text[quitLen:])
			}
			return text, time.Since(queryAt)
		}
	}
	t.Fatalf("the shell never reported; screen:\n%q", screen.String())
	return "", 0
}

// A terminal-generated byte must not reach the shell under tmux either, and what is typed during the exit arrives as the keys typed: tmux sends a Ctrl key as a legacy control byte once it has handled the disable, never as the modifyOtherKeys form.
func TestExitLeavesNoStrayBytesForTheShellUnderTmux(t *testing.T) {
	requireTmux(t)
	bin := buildBinary(t)
	for _, tc := range []struct {
		name         string
		extendedKeys bool
		fullscreen   bool
		// typed is sent right behind the quit, so it races the exit.
		typed string
		// allowed is what the shell may receive of it, as od -c prints it with the terminal's echo of a key typed while it still echoed.
		allowed []string
	}{
		{name: "default settings", allowed: []string{""}},
		{name: "fullscreen", fullscreen: true, allowed: []string{""}},
		{name: "extended keys, a Ctrl key typed during the exit", extendedKeys: true, typed: "C-x", allowed: []string{"", `030`, `^X030`}},
		{name: "type-ahead", typed: "l", allowed: []string{"", "l", "ll"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			seedIntegrationSettings(t, dir)
			if tc.fullscreen {
				if err := os.WriteFile(filepath.Join(dir, "agent", "settings.json"), []byte(`{"tuiMode":"fullscreen"}`), 0o600); err != nil {
					t.Fatal(err)
				}
			}
			session := "pig-drain-" + randID()
			if out, err := tmuxCommand("new-session", "-d", "-s", session, "-x", "120", "-y", "34", "bash --noprofile --norc --noediting -i").CombinedOutput(); err != nil {
				t.Fatalf("tmux new-session: %v\n%s", err, out)
			}
			t.Cleanup(func() { _ = killSession(t, session) })
			waitForPanePID(t, session)
			if tc.extendedKeys {
				if out, err := tmuxCommand("set-option", "-s", "extended-keys", "on").CombinedOutput(); err != nil {
					t.Fatalf("tmux set extended-keys: %v\n%s", err, out)
				}
			}
			if out, err := tmuxCommand("send-keys", "-t", session, exitDrainLaunch(dir, bin), "Enter").CombinedOutput(); err != nil {
				t.Fatalf("launch pig: %v\n%s", err, out)
			}
			waitForPaneText(t, session, interactiveReadyMarker, 30*time.Second)
			time.Sleep(300 * time.Millisecond)
			// pipe-pane copies the bytes pig writes before tmux parses them: the proof that these runs take the sentinel path, which ends its writes with a DA1 query after the bracketed-paste disable (Pi's timer drain writes none).
			written := filepath.Join(t.TempDir(), "pane-output")
			if out, err := tmuxCommand("pipe-pane", "-t", session, "cat >> "+shQuote(written)).CombinedOutput(); err != nil {
				t.Fatalf("pipe-pane: %v\n%s", err, out)
			}
			if out, err := tmuxCommand("send-keys", "-t", session, "-l", "/quit\r").CombinedOutput(); err != nil {
				t.Fatalf("quit: %v\n%s", err, out)
			}
			if tc.typed != "" {
				args := []string{"send-keys", "-t", session}
				if len(tc.typed) == 1 {
					args = append(args, "-l")
				}
				if out, err := tmuxCommand(append(args, tc.typed)...).CombinedOutput(); err != nil {
					t.Fatalf("type-ahead: %v\n%s", err, out)
				}
			}
			waitForPaneText(t, session, "SHELLEND", 30*time.Second)
			out, err := tmuxCommand("capture-pane", "-p", "-J", "-t", session).Output()
			if err != nil {
				t.Fatal(err)
			}
			if pipe, err := os.ReadFile(written); err != nil {
				t.Fatal(err)
			} else if off, _, found := bytes.Cut(pipe, []byte("\x1b[?2004l")); !found || !bytes.Contains(pipe[len(off):], []byte("\x1b[c")) {
				t.Fatalf("pig did not end with the DA1 query after the bracketed-paste disable, so this run was not the sentinel exit; it wrote %q", pipe)
			}
			got := shellReceived(t, string(out))
			for _, ok := range tc.allowed {
				if got == ok {
					return
				}
			}
			t.Fatalf("the shell received %q after pig exited, want one of %q", got, tc.allowed)
		})
	}
}
