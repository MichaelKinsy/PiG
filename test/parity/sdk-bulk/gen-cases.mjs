// Writes the case sources test/parity/sdk-vectors/cases/pi-tui/<export>.mjs (the inputs automation/gen/generate-sdk-vectors.mjs runs Pi's
// functions over) from the bulk corpora's inputs. Only inputs are taken from the corpora; every expected value is Pi's own output.
// Usage: node gen-cases.mjs   (from this directory)
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.resolve(here, "../sdk-vectors/cases/pi-tui");
fs.mkdirSync(out, { recursive: true });
const load = (n) => JSON.parse(fs.readFileSync(path.join(here, n), "utf8"));
const text = load("tui-text.json"), keys = load("tui-keys.json"), fuzzy = load("tui-fuzzy.json"), colors = load("tui-colors.json"), term = load("tui-terminal.json");
const every = (list, n) => list.filter((_, i) => i % Math.max(1, Math.floor(list.length / n)) === 0).slice(0, n);
const write = (name, cases, callSource) => {
	const body = `// Generated by test/parity/sdk-bulk/gen-cases.mjs; inputs only.\nexport const cases = ${JSON.stringify(cases.map((args, i) => ({ name: `case ${String(i).padStart(4, "0")}`, args })), null, 0).replace(/\},\{/g, "},\n{")};\n${callSource ?? ""}`;
	fs.writeFileSync(path.join(out, `${name}.mjs`), body);
};
write("visibleWidth", every(text.visibleWidth, 300).map((r) => [r[0]]));
write("stripTerminalSequences", every(text.strip, 200).map((r) => [r[0]]));
write("truncateToWidth", every(text.truncate, 400).map((r) => (r[2] === null ? [r[0], r[1]] : [r[0], r[1], r[2], r[3]])));
write("wrapTextWithAnsi", every(text.wrap, 300).map((r) => [r[0], r[1]]));
write("sliceByColumn", every(text.slice, 300).map((r) => [r[0], r[1], r[2], r[3]]));
write("getOsc8LinkAtColumn", every(text.link, 150).map((r) => [r[0], r[1]]));
write("fuzzyMatch", every(fuzzy.match, 300).map((r) => [r[0], r[1]]));
write("fuzzyFilter", fuzzy.filter.slice(0, 120).map((r) => [r[0], r[1]]), "export const call = (fn, items, query) => fn(items, query, (item) => item);\n");
const rows = keys.modes[0].rows;
write("parseKey", every(keys.data, 400).map((d) => [d]));
write("isKeyRelease", every(keys.data, 200).map((d) => [d]));
write("isKeyRepeat", every(keys.data, 200).map((d) => [d]));
write("decodeKittyPrintable", every(keys.data, 400).map((d) => [d]));
const matchCases = [];
keys.data.forEach((d, i) => {
	for (const j of rows[i][5].slice(0, 2)) matchCases.push([d, keys.universe[j]]);
	matchCases.push([d, keys.universe[(i * 7) % keys.universe.length]]);
});
write("matchesKey", every(matchCases, 600));
write("hyperlink", term.hyperlink.map((r) => [r[0], r[1]]));
write("CURSOR_MARKER", [[]], "export const call = (v) => v;\n");
const ops = (name) => colors.ops.filter((o) => o[0] === name).map((o) => o[1].map((a) => (a === null ? { $: "NaN" } : a)));
for (const name of ["parseColor", "rgbColor", "oklchColor", "okhslColor", "indexedColor", "colorToRgb", "colorToHex", "colorToOklch", "colorToOkhsl", "foregroundAnsi", "backgroundAnsi", "mixColors", "styleText"]) {
	const list = ops(name).filter((a) => !a.some((x) => x && x.$));
	write(name, every(list, 120));
}
write("styleTextWithAnsi", colors.ops.filter((o) => o[0] === "styleTextWithAnsi").slice(0, 100).map((o) => o[1]));
