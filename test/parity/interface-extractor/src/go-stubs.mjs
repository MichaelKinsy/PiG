// packageEntries returns the source files behind the package's public
// subpath exports: the explicit `source` condition when present, otherwise the
// dist type file mapped back to src/*.ts.
export function packageEntries(packageDir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(packageDir, "package.json"), "utf8"));
  const entries = [];
  const add = (subpath, relative) => {
    if (!relative) return;
    let source = relative.replace(/^\.\//, "");
    if (!source.endsWith(".ts") || source.endsWith(".d.ts")) {
      source = source.replace(/^dist\//, "src/").replace(/\.d\.ts$|\.js$/, ".ts");
    }
    const absolute = path.join(packageDir, source);
    if (fs.existsSync(absolute)) entries.push({ subpath, file: absolute });
  };
  const exportsField = manifest.exports;
  if (exportsField && typeof exportsField === "object") {
    for (const [subpath, target] of Object.entries(exportsField)) {
      if (subpath.endsWith("package.json")) continue;
      if (typeof target === "string") add(subpath, target);
      else add(subpath, target.source ?? target.types ?? target.import ?? target.default);
    }
  }
  if (entries.length === 0) {
    for (const candidate of [manifest.types, manifest.main, "src/index.ts"]) {
      add(".", candidate);
      if (entries.length) break;
    }
  }
  return entries;
}

function workspacePaths(sourceRoot) {
  const paths = {};
  const packagesDir = path.join(sourceRoot, "packages");
  for (const name of fs.readdirSync(packagesDir)) {
    const manifestPath = path.join(packagesDir, name, "package.json");
    if (!fs.existsSync(manifestPath)) continue;
    const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
    if (!manifest.name) continue;
    for (const entry of packageEntries(path.join(packagesDir, name))) {
      const spec = entry.subpath === "." ? manifest.name : `${manifest.name}/${entry.subpath.replace(/^\.\//, "")}`;
      paths[spec] = [entry.file];
    }
  }
  return paths;
}

// ── Go type rendering ───────────────────────────────────────────────────────

class Renderer {
  constructor(checker, owned, imports, typeIndex = new Map()) {
    this.checker = checker;
    this.owned = owned; // TS symbol → { goName, kind }
    this.imports = imports;
    this.typeIndex = typeIndex; // interned TS type → owned alias (TypeBox Static<> results)
    this.rendering = undefined;
    this.foreign = undefined;
    this.typeParams = new Set();
  }

  ownedName(symbol) {
    if (!symbol) return undefined;
    let resolved = symbol;
    if (resolved.flags & ts.SymbolFlags.Alias) resolved = this.checker.getAliasedSymbol(resolved);
    return this.owned.get(resolved);
  }

  // type renders a Go type for a TypeScript type. Unknown and foreign shapes
  // become `any`; the doc comment keeps the upstream spelling.
  type(type, depth = 0) {
    const checker = this.checker;
    if (depth > 6) return "any";
    const f = type.flags;
    if (f & (ts.TypeFlags.Any | ts.TypeFlags.Unknown | ts.TypeFlags.Never)) return "any";
    if (f & ts.TypeFlags.TypeParameter) {
      // Only the declaration's own type parameters are in Go scope; a generic
      // method's or callback's parameters (Go has none) erase to any.
      const name = goName(type.symbol?.name ?? "T");
      return this.typeParams.has(name) ? name : "any";
    }
    const indexed = this.typeIndex.get(type);
    if (indexed && indexed !== this.rendering) return this.reference(indexed, undefined, depth);
    const foreignIndexed = this.foreign?.typeIndex.get(type);
    if (foreignIndexed) return this.foreignReference(foreignIndexed);
    if (type.aliasSymbol) {
      const foreignAlias = this.foreignName(type.aliasSymbol, type.aliasTypeArguments, depth);
      if (foreignAlias) return foreignAlias;
      const owned = this.ownedName(type.aliasSymbol);
      if (owned && owned.kind !== "value") return this.reference(owned, type.aliasTypeArguments, depth);
    }
    if (f & (ts.TypeFlags.String | ts.TypeFlags.StringLiteral | ts.TypeFlags.TemplateLiteral)) return "string";
    if (f & (ts.TypeFlags.Number | ts.TypeFlags.NumberLiteral)) return "float64";
    if (f & (ts.TypeFlags.Boolean | ts.TypeFlags.BooleanLiteral)) return "bool";
    if (f & (ts.TypeFlags.BigInt | ts.TypeFlags.BigIntLiteral)) {
      this.imports.add("math/big");
      return "*big.Int";
    }
    if (f & (ts.TypeFlags.Void | ts.TypeFlags.Undefined | ts.TypeFlags.Null)) return "struct{}";
    if (f & ts.TypeFlags.ESSymbol || f & ts.TypeFlags.UniqueESSymbol) return "any";
    if (isTupleLike(checker, type)) return "[]any";
    if (type.isUnion()) return this.union(type, depth);
    if (type.isIntersection()) return "any";
    const symbol = type.getSymbol();
    const name = symbol?.name;
    if (name === "Uint8Array" || name === "ArrayBuffer" || name === "Buffer") return "[]byte";
    if (name === "Promise" || name === "PromiseLike") {
      const [inner] = checker.getTypeArguments(type);
      return inner ? this.type(inner, depth + 1) : "any";
    }
    if (checker.isArrayType(type) || name === "ReadonlyArray") {
      const [element] = checker.getTypeArguments(type);
      return `[]${element ? this.elem(element, depth) : "any"}`;
    }
    if (checker.isTupleType(type)) return "[]any";
    if (name === "Map" || name === "ReadonlyMap") {
      const [key, value] = checker.getTypeArguments(type);
      return `map[${this.mapKey(key, depth)}]${value ? this.elem(value, depth) : "any"}`;
    }
    if (name === "Set" || name === "ReadonlySet") {
      const [key] = checker.getTypeArguments(type);
      return `map[${this.mapKey(key, depth)}]struct{}`;
    }
    if (name === "Error" || name === "TypeError" || name === "RangeError") return "error";
    if (name === "Date") {
      this.imports.add("time");
      return "time.Time";
    }
    if (name === "AbortSignal") {
      this.imports.add("context");
      return "context.Context";
    }
    const foreignNamed = this.foreignName(symbol, f & ts.TypeFlags.Object && type.objectFlags & ts.ObjectFlags.Reference ? checker.getTypeArguments(type) : undefined, depth);
    if (foreignNamed) return foreignNamed;
    const owned = this.ownedName(symbol);
    if (owned && owned.kind !== "value") {
      const args = f & ts.TypeFlags.Object && type.objectFlags & ts.ObjectFlags.Reference ? checker.getTypeArguments(type) : undefined;
      return this.reference(owned, args, depth);
    }
    const signatures = type.getCallSignatures();
    if (signatures.length > 0 && type.getProperties().length === 0) return this.funcType(signatures[0], depth);
    const indexType = type.getStringIndexType?.();
    if (indexType && type.getProperties().length === 0) return `map[string]${this.elem(indexType, depth)}`;
    return "any";
  }

  // foreignName renders a symbol exported by another workspace package that
  // the caller mapped to a Go import path (--import); others stay `any`.
  foreignName(symbol, args, depth = 0) {
    if (!symbol || !this.foreign) return undefined;
    let resolved = symbol;
    if (resolved.flags & ts.SymbolFlags.Alias) resolved = this.checker.getAliasedSymbol(resolved);
    const entry = this.foreign.symbols.get(resolved);
    return entry ? this.foreignReference(entry, args, depth) : undefined;
  }

  foreignReference(entry, args, depth = 0) {
    this.imports.add(entry.importPath);
    const typeArgs = entry.typeParameterCount > 0
      ? `[${Array.from({ length: entry.typeParameterCount }, (_, i) => (args?.[i] ? this.type(args[i], depth + 1) : "any")).join(", ")}]`
      : "";
    return `${entry.kind === "class" ? "*" : ""}${entry.alias}.${entry.goName}${typeArgs}`;
  }

  reference(owned, args, depth) {
    const typeArgs = owned.typeParameterCount > 0
      ? `[${Array.from({ length: owned.typeParameterCount }, (_, i) => (args?.[i] ? this.type(args[i], depth + 1) : "any")).join(", ")}]`
      : "";
    return `${owned.kind === "class" ? "*" : ""}${owned.goName}${typeArgs}`;
  }

  elem(type, depth) {
    return this.type(type, depth + 1);
  }

  mapKey(type, depth) {
    if (!type) return "string";
    const rendered = this.type(type, depth + 1);
    return ["string", "float64", "bool"].includes(rendered) || /^\*?[A-Z]/.test(rendered) ? rendered : "string";
  }

  union(type, depth) {
    const present = type.types.filter((member) => !(member.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null | ts.TypeFlags.Void)));
    const nullable = present.length !== type.types.length;
    if (present.length === 0) return "struct{}";
    if (present.every((member) => member.flags & ts.TypeFlags.BooleanLike)) return nullable ? "*bool" : "bool";
    if (present.every((member) => member.flags & ts.TypeFlags.StringLike)) return nullable ? "*string" : "string";
    if (present.every((member) => member.flags & ts.TypeFlags.NumberLike)) return nullable ? "*float64" : "float64";
    if (present.length === 1) {
      const inner = this.type(present[0], depth + 1);
      return nullable ? pointerTo(inner) : inner;
    }
    // Promise-or-value returns (`T | Promise<T>`) collapse to T.
    const unwrapped = present.map((member) => (member.getSymbol()?.name === "Promise" ? this.checker.getTypeArguments(member)[0] : member));
    const rendered = new Set(unwrapped.map((member) => (member ? this.type(member, depth + 1) : "any")));
    if (rendered.size === 1) {
      const inner = [...rendered][0];
      return nullable ? pointerTo(inner) : inner;
    }
    return "any";
  }

  // funcType renders a callback; a Promise result becomes an error result too.
  funcType(signature, depth) {
    const { params, results } = this.signature(signature, { depth: depth + 1, withContext: false });
    return `func(${params.map((param) => param.type).join(", ")})${formatResults(results)}`;
  }

  // signature renders Go parameters and results. Async and throwing upstream
  // functions return an error; async functions also take a context first.
  signature(signature, { depth = 0, withContext = false, throws = false } = {}) {
    const checker = this.checker;
    const params = [];
    let async = false;
    const returnType = checker.getReturnTypeOfSignature(signature);
    if (isPromise(returnType) || (returnType.isUnion() && returnType.types.some(isPromise))) async = true;
    if (async && withContext) {
      this.imports.add("context");
      params.push({ name: "ctx", type: "context.Context" });
    }
    signature.getParameters().forEach((parameter, index) => {
      const declaration = parameter.valueDeclaration ?? parameter.declarations?.[0];
      let paramType = checker.getTypeOfSymbolAtLocation(parameter, declaration ?? parameter.declarations?.[0]);
      const rest = declaration && ts.isParameter(declaration) && declaration.dotDotDotToken;
      if (paramType.symbol?.name === "AbortSignal" || (paramType.isUnion?.() && paramType.types.some((t) => t.symbol?.name === "AbortSignal"))) {
        if (!withContext || !async) {
          this.imports.add("context");
          params.push({ name: "ctx", type: "context.Context" });
        }
        return;
      }
      if (rest && checker.isArrayType(paramType)) {
        const [element] = checker.getTypeArguments(paramType);
        params.push({ name: paramName(parameter.name, index), type: `...${element ? this.type(element, depth + 1) : "any"}` });
        return;
      }
      let rendered = this.type(paramType, depth + 1);
      const optional = declaration && ts.isParameter(declaration) && (declaration.questionToken || declaration.initializer);
      // An omitted options object is the zero value of a struct whose fields are all optional.
      if (optional && isScalar(rendered)) rendered = pointerTo(rendered);
      params.push({ name: paramName(parameter.name, index), type: rendered });
    });
    const results = [];
    const predicate = checker.getTypePredicateOfSignature(signature);
    if (predicate) results.push("bool");
    else {
      const inner = async && isPromise(returnType) ? checker.getTypeArguments(returnType)[0] ?? returnType : returnType;
      if (!(inner.flags & (ts.TypeFlags.Void | ts.TypeFlags.Undefined | ts.TypeFlags.Never))) {
        const rendered = this.type(inner, depth + 1);
        if (rendered !== "struct{}" && rendered !== "*struct{}") results.push(rendered);
      }
    }
    if (async || throws) results.push("error");
    return { params: dedupeParams(params), results, async };
  }
}

// isTupleLike reports a tuple, or a union whose every member is a tuple or
// array (Pi's operation vocabularies); Go carries them as []any.
function isTupleLike(checker, type) {
  if (checker.isTupleType(type)) return true;
  if (!type.isUnion()) return false;
  const present = type.types.filter((member) => !(member.flags & (ts.TypeFlags.Undefined | ts.TypeFlags.Null)));
  return present.length > 1 && present.every((member) => checker.isTupleType(member) || checker.isArrayType(member)) && present.some((member) => checker.isTupleType(member));
}

function validField(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) && !name.startsWith("__@");
}

function dedupeParams(params) {
  const seen = new Map();
  return params.map((param) => {
    const count = seen.get(param.name) ?? 0;
    seen.set(param.name, count + 1);
    return count === 0 ? param : { ...param, name: `${param.name}${count + 1}` };
  });
}

function isPromise(type) {
  const name = type.getSymbol()?.name;
  return name === "Promise" || name === "PromiseLike";
}

function isScalar(rendered) {
  return ["string", "float64", "bool"].includes(rendered) || /^[A-Z][A-Za-z0-9_]*$/.test(rendered);
}

// Go names whose types already have a nil value (func, interface, map, slice
// aliases); an optional reference to one is not wrapped in a pointer.
const nilableNames = new Set();
// Structs whose every field is optional; their zero value is the omitted object.
const optionalStructNames = new Set();
// Variants of a sealed union: the Go type is the discriminant, so their
// single-string-literal properties (`type: "hello"`) are not fields.
const sealedMemberNames = new Set();

function pointerTo(rendered) {
  const base = rendered.replace(/\[.*\]$/, "");
  if (rendered === "struct{}" || nilableNames.has(base) || optionalStructNames.has(base)) return rendered;
  if (rendered.startsWith("*") || rendered.startsWith("[]") || rendered.startsWith("map[") || rendered.startsWith("func(") || rendered === "any" || rendered === "error" || rendered.startsWith("context.")) return rendered;
  return `*${rendered}`;
}

function formatResults(results) {
  if (results.length === 0) return "";
  if (results.length === 1) return ` ${results[0]}`;
  return ` (${results.join(", ")})`;
}

function zeroReturn() {
  return "";
}

