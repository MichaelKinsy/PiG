// gen-go-stubs turns one upstream package's public TypeScript API into a
// compiling Go skeleton for a porter: one *_stub.go file per upstream source
// file with Pi's exported names, doc comments citing upstream file:line, and
// bodies that panic with "unported: <upstream symbol>"; one
// *_upstream_test.go skeleton per upstream test file with a Go subtest per
// it()/test() case; and the test-mapping rows those files support.
//
// The generator owns only files that start with its header and whose recorded
// body hash still matches. It never writes over any other file. Symbols that a
// hand-written Go file in the target directory already declares are omitted,
// and upstream cases that a hand-written Go test cites with an
// `upstream: <test path>:<line>` marker are treated as ported, so re-running
// it after porting shrinks the stubs and flips the ledger rows.

export const HEADER_PREFIX = "// Code generated by gen-go-stubs";
const HASH_PREFIX = "// stubgen:sha256=";

const GO_KEYWORDS = new Set([
  "break", "case", "chan", "const", "continue", "default", "defer", "else", "fallthrough", "for", "func", "go", "goto",
  "if", "import", "interface", "map", "package", "range", "return", "select", "struct", "switch", "type", "var",
  // Predeclared identifiers that would shadow types used by the stubs.
  "any", "error", "string", "bool", "byte", "len", "cap", "new", "make", "copy", "close", "delete", "panic", "append",
  // Packages the stubs import.
  "context", "big", "time", "ctx",
]);

// goName maps an upstream identifier to its exported Go spelling. Pi's
// spelling is kept (Id stays Id); SCREAMING_SNAKE constants become PascalCase
// words (PROTOCOL_VERSION → ProtocolVersion), as the existing ports do.
export function goName(name) {
  const bare = name.replace(/^[#_$]+/, "");
  if (/^[A-Z0-9_]+$/.test(bare) && bare.includes("_")) {
    return bare.split("_").filter(Boolean).map((word) => word[0] + word.slice(1).toLowerCase()).join("");
  }
  if (bare === "") return "X";
  const out = bare[0].toUpperCase() + bare.slice(1);
  return out.replace(/[^A-Za-z0-9_]/g, "_");
}

function paramName(name, index) {
  let out = name.replace(/[^A-Za-z0-9_]/g, "");
  if (!out) out = `arg${index}`;
  if (/^[0-9]/.test(out)) out = `arg${out}`;
  if (GO_KEYWORDS.has(out)) out = `${out}Value`;
  return out;
}

function sha256(text) {
  return crypto.createHash("sha256").update(text).digest("hex");
}

function normalizePath(value) {
  return value.split(path.sep).join("/");
}

