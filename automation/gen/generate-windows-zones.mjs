#!/usr/bin/env node
// Generates internal/yaml12/windowszones_gen.go: CLDR's IANA zone for each Windows time zone key name and territory.
//
// Usage: node automation/gen/generate-windows-zones.mjs [windowsZones.xml] > internal/yaml12/windowszones_gen.go   (make windows-zones)
//
// Node's ICU resolves the host zone on Windows from the registry's TimeZoneKeyName through CLDR's windowsZones data (ICU's uprv_detectWindowsTimeZone calls ucal_getTimeZoneIDForWindowsID with the user's region, which selects that territory's first listed zone and falls back to the territory-001 mapping). Without an argument the script downloads common/supplemental/windowsZones.xml from the CLDR release that matches Node's ICU (process.versions.cldr) and records its SHA-256, so the committed output can be checked against the same file.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

let xml;
let source;
if (process.argv[2]) {
  xml = readFileSync(process.argv[2], "utf8");
  source = process.argv[2];
} else {
  const release = `release-${process.versions.cldr.split(".")[0]}`;
  source = `https://raw.githubusercontent.com/unicode-org/cldr/${release}/common/supplemental/windowsZones.xml`;
  const response = await fetch(source);
  if (!response.ok) throw new Error(`${source}: ${response.status}`);
  xml = await response.text();
}
const digest = createHash("sha256").update(xml).digest("hex");

const zones = new Map();
for (const match of xml.matchAll(/<mapZone other="([^"]+)" territory="([^"]+)" type="([^"]+)"\s*\/>/g)) {
  const key = `${match[1]}|${match[2]}`;
  if (zones.has(key)) throw new Error(`duplicate ${match[1]} ${match[2]}`);
  // ICU takes the first zone of a territory's list.
  zones.set(key, match[3].split(" ")[0]);
}
if (zones.size < 400) throw new Error(`only ${zones.size} mappings in ${source}`);
for (const key of zones.keys()) {
  const [windows] = key.split("|");
  if (!zones.has(`${windows}|001`)) throw new Error(`${windows} has no territory-001 mapping`);
}

for (const [key, iana] of zones) {
  try {
    new Intl.DateTimeFormat("en-US", { timeZone: iana });
  } catch {
    throw new Error(`${key}: Node does not know ${iana}`);
  }
}

const quote = (s) => JSON.stringify(s);
const out = [];
out.push("// Code generated by automation/gen/generate-windows-zones.mjs; DO NOT EDIT.");
out.push("");
out.push(`// Source: CLDR ${process.versions.cldr} windowsZones.xml, SHA-256 ${digest}.`);
out.push(`// Node ${process.version}, ICU ${process.versions.icu}.`);
out.push("");
out.push("package yaml12");
out.push("");
out.push("var windowsZones = []windowsZone{");
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const entries = [...zones].map(([key, iana]) => [...key.split("|"), iana]);
entries.sort((a, b) => compare(a[0], b[0]) || compare(a[1], b[1]));
for (const [windows, territory, iana] of entries) {
  out.push(`\t{${quote(windows)}, ${quote(territory)}, ${quote(iana)}},`);
}
out.push("}");
out.push("");
process.stdout.write(out.join("\n"));
