//go:build ignore

// Command pack-pigdocs writes the files the docs bundle embeds: pages.zst, the pages of internal/pigdocs/content as one zstd frame (the page
// bytes back to back in name order), and pages_gen.go, the page names, sizes and content digest pig reads without decoding the frame. Run by
// `go generate` in internal/pigdocs; TestPackMatchesContent fails when the pack and content/*.md disagree.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/MichaelKinsy/PiG/internal/zstdblob"
)

func main() {
	files, err := filepath.Glob("content/*.md")
	if err != nil {
		fail(err)
	}
	slices.Sort(files)
	var raw bytes.Buffer
	// the digest names the bundle directory: sha256 over name, size and contents of every page in name order
	digest := sha256.New()
	var names, sizes strings.Builder
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			fail(err)
		}
		name := filepath.Base(file)
		fmt.Fprintf(digest, "%s\x00%d\x00", name, len(data))
		digest.Write(data)
		raw.Write(data)
		fmt.Fprintf(&names, "\t%q,\n", name)
		fmt.Fprintf(&sizes, "\t%d,\n", len(data))
	}
	if err := writePack("pages.zst", raw.Bytes()); err != nil {
		fail(err)
	}
	src := fmt.Sprintf("// Code generated by automation/gen/pack-pigdocs.go; DO NOT EDIT.\n\npackage pigdocs\n\n// pageNames lists the pages of pages.zst in name order.\nvar pageNames = [...]string{\n%s}\n\n// pageSizes holds the byte size of each page of pageNames.\nvar pageSizes = [...]int{\n%s}\n\n// contentDigest is the digest of the pages: sha256 over \"name\\x00size\\x00contents\" of each page in name order, in hex.\nconst contentDigest = %q\n", names.String(), sizes.String(), hex.EncodeToString(digest.Sum(nil)))
	formatted, err := format.Source([]byte(src))
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("pages_gen.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

// writePack writes the zstd frame of raw to name. An existing name that already holds raw is left alone, so a library upgrade does not rewrite
// committed bytes.
func writePack(name string, raw []byte) error {
	if existing, err := os.ReadFile(name); err == nil {
		if held, err := zstdblob.Decode(existing); err == nil && bytes.Equal(held, raw) {
			return nil
		}
	}
	return os.WriteFile(name, zstdblob.Encode(raw), 0o644)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "pack-pigdocs:", err)
	os.Exit(1)
}
