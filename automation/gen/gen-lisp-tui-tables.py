#!/usr/bin/env python3
"""Generate extensions/sdk-lisp/src/tui-tables.lisp from the Python SDK's tables (extensions/sdk-py/pig_sdk/tui/_tables.py, which
tui/widthx/sdk_tables_test.go keeps equal to Pi's width tables, _lower.py and _tui_keybindings.py, which test/parity/sdk-bulk/gen.mjs generates from Node).

    python3 automation/gen/gen-lisp-tui-tables.py          write the file
    python3 automation/gen/gen-lisp-tui-tables.py --check  fail when the checked-in file differs
"""

import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TUI = ROOT / "extensions" / "sdk-py" / "pig_sdk" / "tui"
OUT = ROOT / "extensions" / "sdk-lisp" / "src" / "tui-tables.lisp"


def load(name):
    spec = importlib.util.spec_from_file_location(name, TUI / (name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def lower_runs(table):
    """(lo, hi, stride, delta) runs of one-to-one lowercase mappings, and the (code point, string) mappings that are not one-to-one."""
    keys = sorted(table)
    runs, multi = [], []
    i = 0
    while i < len(keys):
        k = keys[i]
        if len(table[k]) != 1:
            multi.append((k, table[k]))
            i += 1
            continue
        delta = ord(table[k]) - k
        stride = 1

        def same(a, b):
            return len(table[b]) == 1 and ord(table[b]) - b == delta and b - a == stride

        if i + 1 < len(keys) and keys[i + 1] - k in (1, 2) and len(table[keys[i + 1]]) == 1 and ord(table[keys[i + 1]]) - keys[i + 1] == delta:
            stride = keys[i + 1] - k
        j = i
        while j + 1 < len(keys) and same(keys[j], keys[j + 1]):
            j += 1
        runs.append((k, keys[j], stride, delta))
        i = j + 1
    return runs, multi


def generate():
    tables = load("_tables")
    lower = load("_lower").JS_LOWER
    definitions = load("_tui_keybindings").TUI_KEYBINDING_DEFINITIONS
    runs, multi = lower_runs(lower)
    out = [";;;; SPDX-License-Identifier: MIT", ";;;; Code generated by automation/gen/gen-lisp-tui-tables.py; DO NOT EDIT.", "(in-package #:pig)", ""]
    ranges = tables.PROP_RANGES
    out.append(";; Upper bound and property bits of each range, sorted; the ranges cover 0..#x10FFFF.")
    out.append("(defparameter *tui-range-highs* #(" + " ".join(str(r[1]) for r in ranges) + "))")
    out.append("(defparameter *tui-range-props* #(" + " ".join(str(r[2]) for r in ranges) + "))")
    out.append("")
    out.append(";; Multi-code-point RGI emoji sequences: code points in hex, one sequence per ';'.")
    seqs = sorted(tables.RGI_SEQUENCES)
    out.append('(defparameter *tui-rgi-text* "' + ";".join(" ".join("%x" % ord(c) for c in s) for s in seqs) + '")')
    out.append("")
    out.append(";; String.prototype.toLowerCase: (lo hi stride delta) runs of one-to-one mappings, then the rest as (code point . string of code points).")
    out.append("(defparameter *tui-lower-runs* #(" + " ".join("%d %d %d %d" % r for r in runs) + "))")
    out.append("(defparameter *tui-lower-multi* '(" + " ".join("(%d %s)" % (k, " ".join(str(ord(c)) for c in v)) for k, v in multi) + "))")
    out.append("")
    out.append(";; pi-tui's TUI_KEYBINDINGS: (id (default keys) description).")
    out.append("(defparameter *tui-keybinding-table*\n  '(" + "\n    ".join(
        '(%s (%s) %s)' % (json.dumps(i), " ".join(json.dumps(k) for k in keys), json.dumps(d)) for i, (keys, d) in definitions.items()) + "))")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("%s is stale: run python3 automation/gen/gen-lisp-tui-tables.py" % OUT.relative_to(ROOT))
    else:
        OUT.write_text(text)
