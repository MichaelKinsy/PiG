//go:build ignore

// Command pack-lisp-sdk writes the files the Lisp SDK bundle embeds: sdk.tgz, the SDK's staged sources as one gzip-compressed tar (the sources
// compress to a quarter of their size, which the stock pig binary carries), and bundle_pack.go, the file list and staging hash pig reads without
// decompressing it. Run by `go generate` in extensions/sdk-lisp; TestPackMatchesSource fails when the pack and the sources disagree.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	files, err := filepath.Glob("src/*.lisp")
	if err != nil {
		fail(err)
	}
	files = append(files, "LICENSE", "pig-sdk.asd")
	slices.Sort(files)
	var archive bytes.Buffer
	zw, err := gzip.NewWriterLevel(&archive, gzip.BestCompression)
	if err != nil {
		fail(err)
	}
	tw := tar.NewWriter(zw)
	// the hash pigsdk names a staged SDK by: "staging-v2", then each file's name, size and contents
	digest := sha256.New()
	digest.Write([]byte("staging-v2\x00"))
	var names strings.Builder
	for _, name := range files {
		data, err := os.ReadFile(name)
		if err != nil {
			fail(err)
		}
		if err := tw.WriteHeader(&tar.Header{Name: name, Mode: 0o644, Size: int64(len(data)), Format: tar.FormatPAX}); err != nil {
			fail(err)
		}
		if _, err := tw.Write(data); err != nil {
			fail(err)
		}
		fmt.Fprintf(digest, "%s\x00%d\x00", name, len(data))
		digest.Write(data)
		fmt.Fprintf(&names, "\t%q,\n", name)
	}
	if err := tw.Close(); err != nil {
		fail(err)
	}
	if err := zw.Close(); err != nil {
		fail(err)
	}
	if err := os.WriteFile("sdk.tgz", archive.Bytes(), 0o644); err != nil {
		fail(err)
	}
	src := fmt.Sprintf("// Code generated by automation/gen/pack-lisp-sdk.go; DO NOT EDIT.\n\npackage lispsdk\n\n// bundledFiles lists the files of sdk.tgz, relative to the SDK root, in the order pig stages them.\nvar bundledFiles = []string{\n%s}\n\n// stagedHash is the staging hash of the files, as pigsdk computes it from them: the first 16 hex digits.\nconst stagedHash = %q\n", names.String(), hex.EncodeToString(digest.Sum(nil))[:16])
	formatted, err := format.Source([]byte(src))
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("bundle_pack.go", formatted, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "pack-lisp-sdk:", err)
	os.Exit(1)
}
