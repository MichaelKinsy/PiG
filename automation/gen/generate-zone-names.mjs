#!/usr/bin/env node
// Generates internal/yaml12/zonenames_gen.go: the long time-zone names Node's ICU prints in Date.prototype.toString.
//
// Usage: node automation/gen/generate-zone-names.mjs > internal/yaml12/zonenames_gen.go   (make zone-names)
//
// For every IANA zone ID Node knows, and every link name in automation/gen/zone-links.txt (US/Pacific, Asia/Calcutta, Etc/GMT), the script records when the zone name V8 prints changes between 1970 and 2038. ICU names a link by its own metazone data, not its target's, so each ID is measured separately.
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const linksFile = join(dirname(fileURLToPath(import.meta.url)), "zone-links.txt");

const accepted = (id) => {
  try {
    return new Intl.DateTimeFormat("en-US", { timeZone: id }).resolvedOptions().timeZone;
  } catch {
    return null;
  }
};

// `--scan [zoneinfo-dir]` lists the zoneinfo file names ICU accepts as zones (link names such as US/Pacific, Asia/Calcutta and Etc/GMT) for automation/gen/zone-links.txt. A plain run reads that file, so the output does not depend on the host's zoneinfo directory.
if (process.argv[2] === "--scan") {
  const root = process.argv[3] ?? "/usr/share/zoneinfo";
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) {
        if (entry !== "posix" && entry !== "right") walk(path);
      } else if (/^[A-Z]/.test(entry) && accepted(relative(root, path)) !== null) {
        found.push(relative(root, path));
      }
    }
  };
  walk(root);
  process.stdout.write(found.sort().join("\n") + "\n");
  process.exit(0);
}

const ids = new Set(Intl.supportedValuesOf("timeZone"));
for (const id of readFileSync(linksFile, "utf8").split("\n").filter(Boolean)) {
  const resolved = accepted(id);
  if (resolved === null) continue;
  ids.add(id);
  ids.add(resolved);
}

// V8 names a zone from icu::TimeZone::getDisplayName(isDaylight, LONG) asked at the instant itself, or at the equivalent instant in 2008-2037 for times outside 1970-2038 (the Go side maps those). So the table only has to cover 1970-01-01 to 2038-01-19, the range of a 32-bit second count. For each zone the script reads Date.prototype.toString every twelve hours, finds each change of the printed zone name to the second, and stores the zone's two names and the change instants as unsigned varint deltas in base64. The Go side counts the changes at or before an instant, so the result does not depend on the host's zone data. A zone that prints a third name is an error.
const MAX_SECONDS = 2147483647;
const STEP = 43200;

function timeline(zone) {
  process.env.TZ = zone;
  const nameAt = (seconds) => {
    const text = new Date(seconds * 1000).toString();
    return text.slice(text.indexOf("(") + 1, -1);
  };
  const names = [nameAt(0)];
  const changes = [];
  let previous = names[0];
  for (let seconds = STEP; ; seconds = Math.min(seconds + STEP, MAX_SECONDS)) {
    const name = nameAt(seconds);
    if (name !== previous) {
      let low = seconds - STEP;
      let high = seconds;
      while (high - low > 1) {
        const mid = low + Math.floor((high - low) / 2);
        if (nameAt(mid) === previous) low = mid;
        else high = mid;
      }
      if (names.length === 1) names.push(name);
      if (name !== names[changes.length % 2 === 0 ? 1 : 0]) throw new Error(`${zone}: ${name} is not the alternate of ${previous}`);
      changes.push(high);
      previous = name;
    }
    if (seconds === MAX_SECONDS) break;
  }
  if (nameAt(0) === nameAt(MAX_SECONDS) && changes.length % 2 === 1) throw new Error(`${zone}: odd number of changes`);
  const bytes = [];
  let last = 0;
  for (const at of changes) {
    let delta = at - last;
    last = at;
    while (delta >= 0x80) {
      bytes.push((delta & 0x7f) | 0x80);
      delta = Math.floor(delta / 128);
    }
    bytes.push(delta);
  }
  return { names, changes: Buffer.from(bytes).toString("base64") };
}

const quote = (s) => JSON.stringify(s);
const out = [];
out.push("// Code generated by automation/gen/generate-zone-names.mjs; DO NOT EDIT.");
out.push("");
out.push(`// Node ${process.version}, ICU ${process.versions.icu}, tz ${process.versions.tz}.`);
out.push("");
out.push("package yaml12");
out.push("");
out.push("var zoneTimelines = []zoneTimeline{");
for (const zone of [...ids].sort()) {
  const { names, changes } = timeline(zone);
  out.push(`\t{${quote(zone)}, []string{${names.map(quote).join(", ")}}, ${quote(changes)}},`);
}
out.push("}");
out.push("");
process.stdout.write(out.join("\n"));
