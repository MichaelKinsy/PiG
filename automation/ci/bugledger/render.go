package main

import (
	"encoding/json"
	"fmt"
	"slices"
	"strings"
)

var classTitle = map[string]string{
	ClassOwn:       "PiG's own defect",
	ClassAheadOfPi: "A Pi defect that PiG fixed first",
	ClassPiPort:    "A fix Pi shipped that PiG ported",
}

func marshalJSON(l *Ledger) ([]byte, error) {
	data, err := json.MarshalIndent(l, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// maxShownTests bounds the tests listed per entry on the page; the JSON ledger lists all of them.
const maxShownTests = 8

func cell(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "\\|"), "\n", " ") }

func plural(n int, one, many string) string {
	if n == 1 {
		return fmt.Sprintf("%d %s", n, one)
	}
	return fmt.Sprintf("%d %s", n, many)
}

// renderMarkdown writes the public page. It is generated: edit the sources, not the page.
func renderMarkdown(l *Ledger) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Bug fix ledger\n\n")
	fmt.Fprintf(&b, "<!-- Generated by `make bug-ledger` from the project's commit history, its changelog, and its divergence records. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "This page lists every bug fixed since PiG %s: what users saw, why it happened, what it cost them, where it happened, which commits fixed it, and which tests keep it fixed. `make bug-ledger` regenerates it and `make bug-ledger-check` fails when it is out of date.\n\n", l.Since)
	fmt.Fprintf(&b, "## How to read it\n\n")
	fmt.Fprintf(&b, "- **Source.** Each entry has one source class. *Own defect*: PiG differed from Pi, or failed where Pi does not. *Fixed ahead of Pi*: Pi has the same defect, PiG fixed it first, and the entry names its divergence number (listed by `pig docs show divergences`), the Pi issue, and the condition that removes the difference when Pi fixes it. *Pi fix ported*: Pi shipped the fix and PiG ported it.\n")
	fmt.Fprintf(&b, "- **What counts as a bug.** An entry exists for each item under *Fixed* in the release notes, for each fixed-ahead divergence added since PiG %s, and for each commit titled as a fix that changes shipped code. Commits titled as fixes that change only tests, tooling, generated files or the repair of a merge are not bugs in a release; they are counted at the end of this page.\n", l.Since)
	fmt.Fprintf(&b, "- **Root cause.** The text comes from the fix commit's message or the release note, in that order. *Not recorded* means neither states a cause.\n")
	fmt.Fprintf(&b, "- **User impact.** A class chosen from the wording of the release note: credential exposure, crash or hang, lost data, a failed operation, wrong display, wrong output, or a difference from Pi. It describes the report, not a measured severity.\n")
	fmt.Fprintf(&b, "- **Fix commits.** Short hashes from the project's development history, with the pull request number when the commit has one. *Not yet committed* marks a fix whose release note is written but whose commit is not in history.\n")
	fmt.Fprintf(&b, "- **Tests.** Tests the fix commit adds or names, each checked to exist in the tree. *None recorded* marks a fix whose commit neither adds nor names one.\n\n")
	fmt.Fprintf(&b, "## Summary\n\nEntries are listed by ID. The page carries no totals, so a pull request that adds an entry changes only that entry's lines; `go run ./automation/ci/bugledger -summary` prints the counts by source and the number of entries with no recorded test.\n\n")
	fmt.Fprintf(&b, "| ID | Bug | Source | Platform | Fixed in |\n|---|---|---|---|---|\n")
	for _, e := range l.Entries {
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %s |\n", e.ID, strings.ToLower(e.ID), cell(e.Title), classTitle[e.Class], cell(e.Platform), e.FixedIn)
	}
	b.WriteString("\n## Entries\n")
	for _, e := range l.Entries {
		fmt.Fprintf(&b, "\n### %s\n\n", e.ID)
		fmt.Fprintf(&b, "**%s**\n\n", strings.ReplaceAll(e.Title, "\n", " "))
		fmt.Fprintf(&b, "- **Source:** %s", classTitle[e.Class])
		if e.Divergence != "" {
			fmt.Fprintf(&b, " (divergence %s)", e.Divergence)
		}
		b.WriteString("\n")
		fmt.Fprintf(&b, "- **Symptom:** %s\n", e.Symptom)
		cause := e.RootCause
		if cause == "" {
			cause = "Not recorded."
		}
		fmt.Fprintf(&b, "- **Root cause:** %s\n", cause)
		fmt.Fprintf(&b, "- **User impact:** %s\n", e.Impact)
		fmt.Fprintf(&b, "- **Platform:** %s\n", e.Platform)
		fmt.Fprintf(&b, "- **Fixed in:** %s\n", e.FixedIn)
		if e.Class == ClassAheadOfPi {
			issue := e.PiIssue
			if issue == "" {
				issue = "none recorded"
			}
			fmt.Fprintf(&b, "- **Pi issue:** %s\n", issue)
			if e.RemoveWhen != "" {
				fmt.Fprintf(&b, "- **Removed when Pi fixes it:** %s\n", e.RemoveWhen)
			}
		}
		if len(e.Commits) == 0 {
			b.WriteString("- **Fix commits:** Not yet committed.\n")
		} else {
			var cs []string
			for _, c := range e.Commits {
				s := fmt.Sprintf("`%s` (%s)", c.Hash, c.Date)
				if c.PR != "" {
					s = fmt.Sprintf("`%s` (%s, #%s)", c.Hash, c.Date, c.PR)
				}
				cs = append(cs, s)
			}
			label := "Fix commits"
			if e.CommitsFrom == "release note" {
				label = "Commit that wrote the release note (the fix commit is not identified)"
			}
			fmt.Fprintf(&b, "- **%s:** %s\n", label, strings.Join(cs, ", "))
		}
		if len(e.Tests) == 0 {
			b.WriteString("- **Tests:** None recorded.\n")
		} else {
			var ts []string
			for _, t := range e.Tests[:min(len(e.Tests), maxShownTests)] {
				ts = append(ts, "`"+t+"`")
			}
			more := ""
			if len(e.Tests) > maxShownTests {
				more = fmt.Sprintf(" and %d more in docs/bug-ledger.json", len(e.Tests)-maxShownTests)
			}
			fmt.Fprintf(&b, "- **Tests:** %s%s\n", strings.Join(ts, ", "), more)
		}
		if e.Note != "" {
			fmt.Fprintf(&b, "- **Release note:** %s\n", e.Note)
		}
	}
	if len(l.Divergences) > 0 {
		b.WriteString("\n## Divergences from Pi added in this release\n\nEach divergence record is accounted for here. A divergence that fixes a Pi defect links to its ledger entry; the others are deliberate differences and no bug fix.\n\n| Divergence | Title | Ledger entry |\n|---|---|---|\n")
		for _, d := range l.Divergences {
			entry := "deliberate difference"
			if d.Entry != "" {
				entry = "[" + d.Entry + "](#" + strings.ToLower(d.Entry) + ")"
			}
			fmt.Fprintf(&b, "| %s | %s | %s |\n", d.ID, cell(d.Title), entry)
		}
	}
	if len(l.Exempt) > 0 {
		b.WriteString("\n## Fix-titled commits that are not bugs in a release\n\n")
		var keys []string
		for k := range l.Exempt {
			keys = append(keys, k)
		}
		slices.Sort(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "- %s: %d\n", k, l.Exempt[k])
		}
	}
	return b.String()
}
