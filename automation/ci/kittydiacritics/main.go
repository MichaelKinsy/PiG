// Command kittydiacritics writes the table of the combining characters that number the rows and columns of a Kitty
// Unicode placeholder (coding/extension/host/subprocess/view_mount_image_diacritics.go).
//
// The Kitty graphics protocol (https://sw.kovidgoyal.net/kitty/graphics-protocol/#unicode-placeholders) numbers a
// placeholder cell's row and column with combining characters taken from Unicode 6.0.0: those of combining class 230
// (above the base character) that have no decomposition mapping, without the ones a normalization may fuse with the
// character before them. The input is UnicodeData.txt of that version, from unicode.org under the Unicode licence;
// Go's unicode package holds a later version and is not the source. The rule here reads only that file:
//
//   - general category Mn, canonical combining class 230, an empty decomposition mapping;
//   - not the second character of any canonical decomposition mapping of two characters in the file (U+0300 is the
//     second character of U+00C0's, so U+0041 U+0300 composes and U+0300 is left out);
//   - in the file's order, which is the order of the code points.
//
// Usage, from the repository root:
//
//	go run ./automation/ci/kittydiacritics -ucd UnicodeData.txt          writes the table
//	go run ./automation/ci/kittydiacritics -ucd UnicodeData.txt -list    prints the code points, one per line
//	go run ./automation/ci/kittydiacritics -ucd UnicodeData.txt -check   fails when the committed table differs
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"strings"
)

const (
	unicodeDataURL    = "https://www.unicode.org/Public/6.0.0/ucd/UnicodeData.txt"
	unicodeDataSHA256 = "90b45b777346bef027556f9c6cb3ea5d7d745bd60d6762855c08d8a22d34f771"
	tablePath         = "coding/extension/host/subprocess/view_mount_image_diacritics.go"
)

// selectDiacritics returns the code points of the table, as UnicodeData.txt writes them, from the bytes of the file.
func selectDiacritics(data []byte) ([]string, error) {
	if sum := sha256.Sum256(data); hex.EncodeToString(sum[:]) != unicodeDataSHA256 {
		return nil, fmt.Errorf("the input has sha256 %s; %s has %s", hex.EncodeToString(sum[:]), unicodeDataURL, unicodeDataSHA256)
	}
	return selectLines(string(data)), nil
}

// selectLines applies the rule to the lines of UnicodeData.txt.
func selectLines(data string) []string {
	fused := map[string]bool{}
	var marks []string
	for line := range strings.SplitSeq(data, "\n") {
		fields := strings.Split(line, ";")
		if len(fields) < 6 {
			continue
		}
		// A canonical mapping has no <tag>; one of two characters is a pair that composes.
		if mapping := fields[5]; mapping != "" && !strings.HasPrefix(mapping, "<") {
			if parts := strings.Fields(mapping); len(parts) == 2 {
				fused[parts[1]] = true
			}
		}
		if fields[2] == "Mn" && fields[3] == "230" && fields[5] == "" {
			marks = append(marks, fields[0])
		}
	}
	var out []string
	for _, mark := range marks {
		if !fused[mark] {
			out = append(out, mark)
		}
	}
	return out
}

// table returns the Go source of the table.
func table(points []string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by automation/ci/kittydiacritics from UnicodeData.txt of Unicode 6.0.0. DO NOT EDIT.\n\n")
	b.WriteString("package subprocess\n\n")
	b.WriteString("// kittyDiacritics are the combining characters that number the rows and columns of a Kitty Unicode placeholder: entry\n")
	b.WriteString("// n says row or column n. They are the characters of Unicode 6.0.0 with combining class 230 and no decomposition\n")
	b.WriteString("// mapping that no canonical decomposition of two characters ends with, in the order of their code points, as the\n")
	b.WriteString("// Kitty graphics protocol states (https://sw.kovidgoyal.net/kitty/graphics-protocol/#unicode-placeholders). Source:\n")
	b.WriteString("// " + unicodeDataURL + ", sha256\n")
	b.WriteString("// " + unicodeDataSHA256 + ".\n")
	b.WriteString("var kittyDiacritics = [...]rune{\n")
	for i := 0; i < len(points); i += 12 {
		row := points[i:min(i+12, len(points))]
		b.WriteString("\t0x" + strings.Join(row, ", 0x") + ",\n")
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func run() error {
	ucd := flag.String("ucd", "", "UnicodeData.txt of Unicode 6.0.0")
	list := flag.Bool("list", false, "print the code points and write nothing")
	check := flag.Bool("check", false, "fail when the committed table differs and write nothing")
	flag.Parse()
	if *ucd == "" {
		return fmt.Errorf("name the input: -ucd UnicodeData.txt (%s)", unicodeDataURL)
	}
	data, err := os.ReadFile(*ucd)
	if err != nil {
		return err
	}
	points, err := selectDiacritics(data)
	if err != nil {
		return err
	}
	switch {
	case *list:
		for _, point := range points {
			fmt.Println("0x" + point)
		}
		return nil
	case *check:
		have, err := os.ReadFile(tablePath)
		if err != nil {
			return err
		}
		if !bytes.Equal(have, table(points)) {
			return fmt.Errorf("%s is not what the generator writes: run it without -check", tablePath)
		}
		return nil
	}
	return os.WriteFile(tablePath, table(points), 0o644)
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "kittydiacritics:", err)
		os.Exit(1)
	}
}
