def get_language_from_path(file_path: str) -> Optional[str]:
    """Pi's getLanguageFromPath: the highlight language for the text after the last "." of a path, lower-cased (a path without a dot is its own extension,
    so "Dockerfile" is dockerfile), or None where Pi returns undefined."""
    extension = file_path.rsplit(".", 1)[-1]
    if extension == "":
        return None
    return _LANGUAGE_BY_EXTENSION.get(extension.lower())
