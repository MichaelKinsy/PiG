//! Pi's `getLanguageFromPath` (`modes/interactive/theme/theme.ts`).

/// Pi's `getLanguageFromPath`: the highlight language for the text after the last `.` of a path, lower-cased (a path without a dot is its own extension, so
/// `Dockerfile` is `dockerfile`), or `None` where Pi returns `undefined`.
pub fn get_language_from_path(file_path: &str) -> Option<&'static str> {
    let extension = file_path.rsplit('.').next().unwrap_or(file_path);
    if extension.is_empty() {
        return None;
    }
    Some(match extension.to_lowercase().as_str() {
        "ts" => "typescript",
        "tsx" => "typescript",
        "js" => "javascript",
        "jsx" => "javascript",
        "mjs" => "javascript",
        "cjs" => "javascript",
        "py" => "python",
        "rb" => "ruby",
        "rs" => "rust",
        "go" => "go",
        "java" => "java",
        "kt" => "kotlin",
        "swift" => "swift",
        "c" => "c",
        "h" => "c",
        "cpp" => "cpp",
        "cc" => "cpp",
        "cxx" => "cpp",
        "hpp" => "cpp",
        "cs" => "csharp",
        "php" => "php",
        "sh" => "bash",
        "bash" => "bash",
        "zsh" => "bash",
        "fish" => "fish",
        "ps1" => "powershell",
        "sql" => "sql",
        "html" => "html",
        "htm" => "html",
        "css" => "css",
        "scss" => "scss",
        "sass" => "sass",
        "less" => "less",
        "json" => "json",
        "yaml" => "yaml",
        "yml" => "yaml",
        "toml" => "toml",
        "xml" => "xml",
        "md" => "markdown",
        "markdown" => "markdown",
        "dockerfile" => "dockerfile",
        "makefile" => "makefile",
        "cmake" => "cmake",
        "lua" => "lua",
        "perl" => "perl",
        "r" => "r",
        "scala" => "scala",
        "clj" => "clojure",
        "ex" => "elixir",
        "exs" => "elixir",
        "erl" => "erlang",
        "hs" => "haskell",
        "ml" => "ocaml",
        "vim" => "vim",
        "graphql" => "graphql",
        "proto" => "protobuf",
        "tf" => "hcl",
        "hcl" => "hcl",
        _ => return None,
    })
}
